/// <summary>Severity of a console line, used for colouring.</summary>
public enum MessageKind
{
    /// <summary>Regular Csound output.</summary>
    Normal,
    /// <summary>Message generated by the application itself (start/stop banners, hints).</summary>
    Info,
    /// <summary>Csound warning.</summary>
    Warning,
    /// <summary>Csound error.</summary>
    Error,
}

/// <summary>One line of the console panel.</summary>
/// <param name="Text">Line text without the trailing newline.</param>
/// <param name="Kind">Severity used for colouring.</param>
public sealed partial record ConsoleLine(string Text, MessageKind Kind)
{
    /// <summary>
    /// CSD line number mentioned by the message (Csound reports <c>"... line 18:"</c>), or
    /// <c>null</c>. Clicking such a line jumps to it in the editor.
    /// </summary>
    public int? SourceLine { get; } = ParseLine(Text);

    /// <summary>True for application banners.</summary>
    public bool IsInfo => Kind == MessageKind.Info;

    /// <summary>True for warnings.</summary>
    public bool IsWarning => Kind == MessageKind.Warning;

    /// <summary>True for errors.</summary>
    public bool IsError => Kind == MessageKind.Error;

    /// <summary>A file this line refers to (e.g. a finished recording); clicking shows it in Explorer.</summary>
    public string? FilePath { get; init; }

    /// <summary>True when the line can be clicked (it refers to a source line or a file).</summary>
    public bool HasSourceLine => SourceLine is not null || FilePath is not null;

    /// <summary>Extracts the CSD line number from a Csound message such as <c>"error: ... line 18:"</c>.</summary>
    /// <param name="text">The console line.</param>
    /// <returns>The first positive number following the word «line», or <c>null</c> when there is none.</returns>
    static int? ParseLine(string text)
    {
        var m = LineRef().Match(text);
        return m.Success && int.TryParse(m.Groups[1].Value, out int line) && line > 0 ? line : null;
    }

    /// <summary>Matches «line &lt;number&gt;» (any case); group 1 is the number. Source-generated at compile time.</summary>
    [GeneratedRegex(@"\bline\s+(\d+)\b", RegexOptions.IgnoreCase)]
    private static partial Regex LineRef();
}

/// <summary>Everything the engine needs to run one performance.</summary>
/// <param name="CsdText">Complete CSD text whose <c>&lt;CsOptions&gt;</c> content was already removed.</param>
/// <param name="Options">
/// Command-line options, joined with spaces into one <see cref="CsoundNative.csoundSetOption"/> call.
/// An option may contain spaces only inside double quotes glued to its flag
/// (<c>-i"C:\a b\in.wav"</c>, <c>--env:SSDIR="C:\a b"</c>): Csound 7 honours those quotes but splits
/// on any other space. <see cref="CsdTools.ExtractOptions"/> produces that form from <c>&lt;CsOptions&gt;</c>.
/// </param>
/// <param name="WorkingDirectory">Directory relative file names in the orchestra resolve against, or <c>null</c>.</param>
/// <param name="HostAudio">
/// When set, the application drives the audio device itself through its own WASAPI output
/// (<see cref="WasapiOutput"/>) and Csound only computes samples (<c>csoundSetHostAudioIO</c>).
/// When <c>null</c>, Csound's own real-time module (PortAudio/ASIO, Csound WASAPI…) is used, or
/// nothing at all for offline renders.
/// </param>
/// <param name="Midi">
/// MIDI router whose messages are fed to Csound (host MIDI I/O; Csound's MIDI opcodes, <c>massign</c>,
/// <c>--midi-key</c>… work as usual). <c>null</c> disables MIDI input.
/// </param>
/// <param name="LiveValues">Sample variable values during the performance (Csound debugger; small CPU cost).</param>
/// <param name="InstrumentNames">Named instruments of the orchestra, resolved to numbers for live values.</param>
/// <param name="CsoundDevice">
/// Only when Csound drives a real-time device itself (PortAudio, Csound WASAPI…): a label of the
/// device ("WASAPI · Speakers (X)"; empty = module default). The engine then reports the
/// device's Windows mix rate next to Csound's sr. <c>null</c> otherwise.
/// </param>
public sealed record EngineJob(string CsdText, IReadOnlyList<string> Options, string? WorkingDirectory, HostAudioSettings? HostAudio = null,
    bool LiveValues = false, IReadOnlyList<string>? InstrumentNames = null, Midi.MidiHub? Midi = null, string? CsoundDevice = null);

/// <summary>Settings of the application's own WASAPI output.</summary>
