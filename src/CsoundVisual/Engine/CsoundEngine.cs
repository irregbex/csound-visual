    /// <summary>
    /// Native message callback. Csound calls it on whatever thread produced the message (usually
    /// the performance thread); it only routes the text to the owning engine.
    /// </summary>
    /// <param name="cs">The Csound instance that produced the message.</param>
    /// <param name="attr">Csound message attributes (<c>CSOUNDMSG_*</c> type bits plus colour bits).</param>
    /// <param name="str">UTF-8 text fragment; not necessarily a whole line, may contain several lines.</param>
    /// <remarks>
    /// Messages printed before <c>Instances[cs]</c> is set (inside <c>csoundCreate</c>) or after
    /// it is removed are dropped.
    /// </remarks>
    [UnmanagedCallersOnly(CallConvs = [typeof(CallConvCdecl)])]
    static void OnMessage(IntPtr cs, int attr, IntPtr str)
    {
        if (str == IntPtr.Zero || !Instances.TryGetValue(cs, out var engine))
            return;
        engine.AppendMessage(Marshal.PtrToStringUTF8(str) ?? "", attr);
    }

    /// <summary>Joins message fragments into complete lines and posts each finished line.</summary>
    /// <param name="text">The decoded fragment.</param>
    /// <param name="attr">Csound message attributes of the fragment.</param>
    /// <remarks>
    /// A line split across several callbacks takes the kind of the fragment that carries its '\n'.
    /// </remarks>
    void AppendMessage(string text, int attr)
    {
        // Csound also sends plain informational text ("closing device", "overall amps") with the
        // error attribute, so real errors are detected from the text in Post(). Only the warning
        // attribute is trusted.
        MessageKind kind = (attr & CsoundNative.CSOUNDMSG_TYPE_MASK) == CsoundNative.CSOUNDMSG_WARNING
            ? MessageKind.Warning
            : MessageKind.Normal;

        lock (partialLine)
        {
            text = AnsiEscape().Replace(text, "");
            int start = 0;
            for (int nl; (nl = text.IndexOf('\n', start)) >= 0; start = nl + 1)
            {
                partialLine.Append(text, start, nl - start);
                Post(partialLine.ToString().TrimEnd('\r'), kind);
                partialLine.Clear();
            }
            partialLine.Append(text, start, text.Length - start);
        }
    }

    /// <summary>Posts whatever is left in the partial line buffer (used when a run ends).</summary>
    void FlushPartialLine()
    {
        lock (partialLine)
        {
            if (partialLine.Length > 0)
                Post(partialLine.ToString(), MessageKind.Normal);
            partialLine.Clear();
        }
    }

    /// <summary>Classifies a line by its text when the attribute did not, then enqueues it for the UI.</summary>
    /// <param name="line">Complete line, without newline.</param>
    /// <param name="kind">Kind already known; <see cref="MessageKind.Normal"/> lets the text decide.</param>
    /// <remarks>
    /// Thread-safe (lock-free queue); called from the performance thread, the message callback and
    /// the invoke/hook helpers. The text heuristic is deliberately simple: any line containing
    /// «error» is red, «warning» yellow — so an informational line that merely mentions the word is
    /// coloured too.
    /// </remarks>
    void Post(string line, MessageKind kind)
    {
        if (kind == MessageKind.Normal)
        {
            if (line.Contains("error", StringComparison.OrdinalIgnoreCase))
                kind = MessageKind.Error;
            else if (line.Contains("warning", StringComparison.OrdinalIgnoreCase))
                kind = MessageKind.Warning;
        }
        Messages.Enqueue(new ConsoleLine(line, kind));
    }

    /// <summary>Matches ANSI colour escape sequences, which Csound may embed in messages.</summary>
    [GeneratedRegex(@"\x1B\[[0-9;]*m")]
    private static partial Regex AnsiEscape();
