// CsoundEngine.cs — the heart of the application: runs Csound 7 performances.
//
// Role: owns one native CSOUND* instance per run, on a dedicated «Csound performance» thread, and is
// the ONLY code that calls the Csound API while a performance is active. Everything else in the app
// (the editor's Play button, the live widgets, the piano roll and step sequencer, MIDI, Paint Rooms,
// Ableton Link, the VST3 insert chain, the debugger) talks to it through thread-safe request queues
// and reads lock-free snapshots of its state. MainWindow creates one engine and keeps it for the
// lifetime of the app; tools such as Paint Rooms share it.
//
// The class is split into partial files:
//   CsoundEngine.cs          (this file) lifecycle, the two audio loops, meters/scope, tables, console.
//   CsoundEngine.Invoke.cs   «run this action on the Csound thread» (Paint Rooms table uploads).
//   CsoundEngine.CycleHook.cs  per-cycle hook (Ableton Link channels).
//   CsoundEngine.Debugger.cs breakpoints / live values through Csound's debugger API.
//   CsoundEngine.Inserts.cs  VST3 insert chain applied to spout (app WASAPI engine only).
//
// Two audio paths:
//   • App WASAPI engine (EngineJob.HostAudio set): the app opens the Windows device itself
//     (Audio/WasapiOutput), tells Csound csoundSetHostAudioIO (Csound then only computes samples into
//     spout and never touches a device), and PerformHost pulls control cycles on demand when the
//     device's event wakes the thread. This path gives exact dropout/DSP-load measurement, live input
//     with drift correction, recording and inserts.
//   • Csound's own I/O (HostAudio null): PortAudio/ASIO/Csound's WASAPI module, or an offline render
//     to a file. Csound blocks inside csoundPerformKsmps on the device; Perform just loops Step().
//
// Csound 7 notes: options are passed in ONE csoundSetOption call (Csound 7 splits it on spaces but
// honours quotes glued to a flag); csoundCompileCSD takes the CSD as TEXT (mode 1); score lines go
// through csoundEventString (async = 0: we are already on the performance thread, between cycles);
// message callbacks deliver UTF-8 fragments that are not necessarily whole lines.

