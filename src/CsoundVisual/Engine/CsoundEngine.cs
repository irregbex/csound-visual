public sealed record HostAudioSettings(string? DeviceId, WasapiMode Mode, LatencyPreset Preset, AudioInputSettings? Input = null);

/// <summary>Live audio input of the application's own WASAPI engine (always shared mode).</summary>
/// <param name="DeviceId">Capture endpoint id, or <c>null</c> for the Windows default recording device.</param>
/// <param name="Loopback">
