/// <summary>Formatting helpers shared by engine-related views.</summary>
public static class ValueFormat
{
    /// <summary>Compact label for a table value ("74", "0.25", "-1").</summary>
    /// <param name="v">The value.</param>
    /// <returns>Integers without decimals, anything else with at most two, invariant culture.</returns>
    public static string ValueLabel(double v) =>
        v.ToString(Math.Abs(v - Math.Round(v)) < 1e-9 ? "0" : "0.##", System.Globalization.CultureInfo.InvariantCulture);
}

/// <summary>A copy of a function table taken while performing, for display.</summary>
/// <param name="Number">Table number (<c>ftgen 0</c> assigns numbers from 101 upwards).</param>
/// <param name="Length">Real table length.</param>
/// <param name="Points">Values, decimated to at most <see cref="CsoundEngine.TablePoints"/> points.</param>
/// <param name="Minimum">Smallest value in the whole table.</param>
/// <param name="Maximum">Largest value in the whole table.</param>
public sealed record TableSnapshot(int Number, int Length, float[] Points, double Minimum, double Maximum)
{
    /// <summary>Label used in the table picker.</summary>
    public string Label => Loc.S($"ftable {Number}  ·  {Length} puntos", $"ftable {Number}  ·  {Length} points");

    /// <inheritdoc/>
    public override string ToString() => Label;
}

/// <summary>
/// Runs one Csound performance at a time on a dedicated thread and exposes its state to the UI.
/// </summary>
/// <remarks>
/// <para>
/// <b>Threading model.</b> Every call into the Csound API happens on the performance thread
/// created by <see cref="Start"/>. The UI never calls Csound directly: it enqueues requests
/// (<see cref="SetControl"/>, <see cref="SendEvent"/>, <see cref="CompileOrc"/>,
/// <see cref="RequestTables"/>) that the performance thread applies between two control cycles,
/// and it reads lock-free snapshots (<see cref="TakePeaks"/>, <see cref="CopyScope"/>,
/// <see cref="Messages"/>, <see cref="ScoreTime"/>). Torn reads on the meter/scope arrays are
/// harmless for display purposes, so no locks are taken on the audio path.
/// </para>
/// <para>
/// <b>Lifetime.</b> A fresh <c>CSOUND*</c> is created for every run and destroyed when it ends,
/// which is the most robust way to guarantee a clean state between runs.
/// </para>
/// </remarks>
public sealed unsafe partial class CsoundEngine
{
    /// <summary>Maximum number of output channels metered.</summary>
    public const int MaxChannels = 8;

    /// <summary>Length of the oscilloscope ring buffer, in samples.</summary>
    public const int ScopeSize = 2048;

    /// <summary>Maximum number of points kept per <see cref="TableSnapshot"/>.</summary>
    public const int TablePoints = 1024;

    /// <summary>Highest table number scanned by <see cref="RequestTables"/>.</summary>
    const int MaxTableNumber = 1000;

    /// <summary>Maps a native instance to its engine so the static message callback can route messages.</summary>
    static readonly ConcurrentDictionary<IntPtr, CsoundEngine> Instances = new();

    // Requests from the UI thread, drained by the performance thread between control cycles.
    // The four queues are independent: there is no ordering guarantee BETWEEN them (a control value
    // and a score line sent in that order may reach Csound in the same cycle in either order). Jobs
    // that need atomic ordering use InvokeOnCsoundThread (CsoundEngine.Invoke.cs).

    /// <summary>
    /// Latest value per control channel name (<see cref="SetControl"/>). A dictionary rather than a
    /// queue so a slider dragged faster than the control rate only sends its last value per cycle.
    /// </summary>
    readonly ConcurrentDictionary<string, double> pendingControls = new();

    /// <summary>Score lines from <see cref="SendEvent"/>, sent with <c>csoundEventString</c> in FIFO order.</summary>
    readonly ConcurrentQueue<string> pendingEvents = new();

    /// <summary>Notes with an absolute start time from <see cref="SendEventAt"/>; p2 is resolved in <see cref="Step"/>.</summary>
    readonly ConcurrentQueue<TimedEvent> pendingTimed = new();

    /// <summary>Orchestra code from <see cref="CompileOrc"/>; holds at most one entry (newer requests replace older ones).</summary>
    readonly ConcurrentQueue<string> pendingOrc = new();

    /// <summary>A note queued by <see cref="SendEventAt"/>: p2 is computed when it reaches Csound.</summary>
    /// <param name="At">Absolute score time of the note start, seconds.</param>
    /// <param name="Instrument">p1 token.</param>
    /// <param name="Duration">p3, seconds.</param>
    /// <param name="Fields">p4 and beyond, already formatted.</param>
    readonly record struct TimedEvent(double At, string Instrument, double Duration, string Fields);

    /// <summary>Timed events arriving later than this (seconds) are dropped instead of played late.</summary>
    const double MaxEventLateness = 0.25;

    /// <summary>Backing field of <see cref="LateEvents"/>; incremented with <see cref="Interlocked"/> on the performance thread.</summary>
    int lateEvents;

    /// <summary>Number of timed events dropped in this run because they arrived too late (see <see cref="SendEventAt"/>).</summary>
    public int LateEvents => Volatile.Read(ref lateEvents);

    /// <summary>Set by <see cref="RequestTables"/> (UI thread), consumed by <see cref="Step"/> (performance thread).</summary>
    volatile bool tablesRequested;

    /// <summary>
    /// Accumulates partial message lines until a '\n' arrives. Also used as the lock object of
    /// <see cref="AppendMessage"/>/<see cref="FlushPartialLine"/>, because Csound may call the
    /// message callback from threads other than the performance thread.
    /// </summary>
    readonly StringBuilder partialLine = new();

    // Written by the performance thread, read by the UI thread. No locks: a torn or slightly stale
    // read only affects one frame of a meter or the scope drawing.

    /// <summary>
    /// Highest absolute sample per output channel (linear, 1.0 = 0 dBFS) since the UI last called
    /// <see cref="TakePeaks"/>. Max-accumulated by <see cref="AnalyseBlock"/>, reset by the reader.
    /// </summary>
    readonly float[] peaks = new float[MaxChannels];

    /// <summary>Oscilloscope ring buffer: the mono mix (L+R)/2 of the output, full scale ±1.0.</summary>
    readonly float[] scope = new float[ScopeSize];

    /// <summary>Next write index into <see cref="scope"/>, i.e. the position of the OLDEST sample.</summary>
    int scopeWrite;

    /// <summary>Backing field of <see cref="ScoreTime"/> (seconds), published after every control cycle.</summary>
    double scoreTime;

    /// <summary>Set by <see cref="Stop"/> (any thread); the audio loops check it once per cycle / device period.</summary>
    volatile bool stopRequested;

    /// <summary>The current performance thread, or <c>null</c> before the first run.</summary>
    Thread? thread;

    /// <summary>MIDI router of the current run (<see cref="EngineJob.Midi"/>), read by the static MIDI callbacks.</summary>
    Midi.MidiHub? midi;

    /// <summary>Live WAV recorder fed from <see cref="Step"/>; swapped atomically by <see cref="StartRecording"/>/<see cref="StopRecording"/>.</summary>
    WavRecorder? recorder;

    /// <summary>Backing field of <see cref="Underruns"/> (Interlocked increments on the performance thread).</summary>
    int underruns;

    /// <summary>Backing field of <see cref="DspLoad"/>: exponentially smoothed ratio, −1 = not measured.</summary>
    double dspLoad;

    /// <summary>Backing field of <see cref="WorstWakeMs"/> (milliseconds).</summary>
    double worstWakeMs;

    // Live audio input (app WASAPI engine only). The capture thread fills input.Ring; Step()
    // pulls one control block per cycle through inputReader into Csound's spin buffer.

    /// <summary>The capture device of this run (opened in <see cref="Run"/>, started in <see cref="StartInput"/>), or <c>null</c>.</summary>
    WasapiInput? input;

    /// <summary>
    /// Resampler + clock-drift controller between the capture ring and Csound's spin. Published with
    /// <see cref="Volatile.Write{T}(ref T, T)"/> only once capture really started, so a non-null value
    /// means «live input is flowing» (<see cref="HasLiveInput"/>).
    /// </summary>
    AdaptiveInputReader? inputReader;

    /// <summary>True once a capture-thread error was printed, so it is reported only once per run.</summary>
    bool inputErrorReported;

    /// <summary>Csound's 0dBFS of this run; input samples (±1.0) are multiplied by it before entering spin.</summary>
    double zeroDbfs = 1;

    /// <summary>Console lines produced by Csound and by the engine, in order. The UI drains it every frame.</summary>
    public ConcurrentQueue<ConsoleLine> Messages { get; } = new();

    /// <summary>True while a performance thread is alive.</summary>
    public bool IsBusy => thread is { IsAlive: true };

    /// <summary>Score time of the current performance, in seconds.</summary>
    public double ScoreTime => Volatile.Read(ref scoreTime);

    /// <summary>Output channel count of the current performance (valid after it started).</summary>
    public int OutputChannels { get; private set; }

    /// <summary>Sample rate of the current performance (valid after it started).</summary>
    public double SampleRate { get; private set; }

    /// <summary>Control block size of the current performance (valid after it started).</summary>
    public int Ksmps { get; private set; }

    /// <summary>
    /// Number of audio dropouts in the current run: the device ran out of samples (shared mode) or
    /// computing one device period took longer than the period itself (both modes).
    /// Only measured with the application's own WASAPI output.
    /// </summary>
    public int Underruns => Volatile.Read(ref underruns);

    /// <summary>
    /// True when the last run ended because the output device stopped consuming samples (the
    /// stalled-device watchdog in <c>PerformHost</c>). Read by the view model after
    /// <see cref="Finished"/> to restart on the Windows default output. Reset at each start.
    /// </summary>
    public bool LastRunOutputStalled { get; private set; }

    /// <summary>
    /// Smoothed DSP load: time spent computing audio divided by the time available for it
    /// (1.0 = 100 %, above that audio breaks up). Only measured with the application's own output; -1 otherwise.
    /// </summary>
    public double DspLoad => Volatile.Read(ref dspLoad);

    /// <summary>Live variable values of the current performance, or <c>null</c> when disabled.</summary>
    public LiveValueMonitor? Live { get; private set; }

    /// <summary>
    /// Longest time between two device wake-ups seen in this run, in milliseconds (app WASAPI
    /// output only). Much more than one period means the audio thread was held up — by the
    /// system, the .NET garbage collector or a slow control cycle.
    /// </summary>
    public double WorstWakeMs => Volatile.Read(ref worstWakeMs);

    /// <summary>Description of the audio stream actually opened (device, mode, rate, format, latency), or <c>null</c>.</summary>
    public string? AudioDescription { get; private set; }

    /// <summary>Input channel count Csound expects (<c>nchnls_i</c>, defaults to nchnls) in the current run.</summary>
    public int InputChannels { get; private set; }

    /// <summary>
    /// How the live input device's channels reach Csound (stereo pair or one input copied to all
    /// channels). Set by the UI thread at any time; the performance thread reads it once per
    /// control block, so a change is heard within one ksmps. An enum field write is atomic.
    /// </summary>
    public Audio.InputRouting InputRouting { get; set; }

    /// <summary>True while a live audio input is feeding Csound (app WASAPI engine with an input device chosen).</summary>
    public bool HasLiveInput => Volatile.Read(ref inputReader) is not null;

    /// <summary>The running input's resampler/drift controller (statistics), or <c>null</c>.</summary>
    public AdaptiveInputReader? InputReader => Volatile.Read(ref inputReader);

    /// <summary>
    /// Copies the input peaks (linear, 1.0 = 0 dBFS, one per capture channel) since the previous
    /// call into <paramref name="dest"/> and resets them; 0 when no live input is running.
    /// </summary>
    public int TakeInputPeaks(Span<float> dest) =>
        HasLiveInput && Volatile.Read(ref input) is { } i ? i.TakePeaks(dest) : 0;

    /// <summary>Raised on the performance thread when a run ends, with its result code (0 = success).</summary>
    public event Action<int>? Finished;

    /// <summary>Raised on the performance thread with the tables captured after <see cref="RequestTables"/>.</summary>
    public event Action<IReadOnlyList<TableSnapshot>>? TablesCaptured;

    /// <summary>Starts a new performance on a dedicated, above-normal priority thread.</summary>
    /// <param name="job">What to compile and how to play it.</param>
    /// <remarks>
    /// Returns immediately; compilation errors are reported on <see cref="Messages"/> and through
    /// <see cref="Finished"/>. Called from the UI thread.
    /// </remarks>
    /// <exception cref="InvalidOperationException">A performance is already running.</exception>
    public void Start(EngineJob job)
    {
        if (IsBusy)
            throw new InvalidOperationException(Loc.S("Csound ya está corriendo.", "Csound is already running."));

        // Reset per-run state. Safe without locks: the previous performance thread has exited
        // (IsBusy is false) and the new one has not been created yet. Requests left over from the
        // previous run are discarded (orchestra code, timed notes); pendingControls/pendingEvents
        // are kept, so a value set while stopped still reaches the next run.
        stopRequested = false;
        tablesRequested = false;
        scoreTime = 0;
        underruns = 0;
        LastRunOutputStalled = false;
        worstWakeMs = 0;
        dspLoad = -1;
        AudioDescription = null;
        OutputLatencySeconds = 0;
        Live = null;
        InputChannels = 0;
        inputErrorReported = false;
        pendingOrc.Clear();
        pendingTimed.Clear();
        lateEvents = 0;
        thread = new Thread(() => Run(job))
        {
            IsBackground = true,
            Name = "Csound performance",
            Priority = ThreadPriority.AboveNormal,
        };
        thread.Start();
    }

    /// <summary>The active live recording, or <c>null</c>.</summary>
    public WavRecorder? Recorder => Volatile.Read(ref recorder);

    /// <summary>Starts recording the live output to a 32-bit float WAV file (while playing).</summary>
    /// <param name="path">Destination WAV file; created/overwritten by <see cref="WavRecorder"/>.</param>
    /// <remarks>
    /// Ignored when nothing is playing (the rate and channel count are not known yet). The recorder
    /// receives exactly what Csound produced after the insert chain, at Csound's sr, before any
    /// device-format conversion. A recorder already running is replaced without being finished.
    /// </remarks>
    public void StartRecording(string path)
    {
        if (!IsBusy || SampleRate <= 0) return;
        Volatile.Write(ref recorder, new WavRecorder(path, (int)SampleRate, OutputChannels));
    }

    /// <summary>Stops the live recording, finishing the file. Returns its path, or <c>null</c>.</summary>
    public string? StopRecording()
    {
        var r = Interlocked.Exchange(ref recorder, null);
        if (r is null) return null;
        r.Dispose();
        return r.Path;
    }

    /// <summary>Asks the running performance to stop after the current control cycle.</summary>
    public void Stop() => stopRequested = true;

    /// <summary>
    /// Sets a control channel. Calls are coalesced: if the UI sends many values for the same
    /// channel within one control cycle, only the last one reaches Csound.
    /// </summary>
    /// <param name="name">Channel name as used by <c>chnget</c> in the orchestra.</param>
    /// <param name="value">New value (applied with <c>csoundSetControlChannel</c> before the next cycle).</param>
    public void SetControl(string name, double value) => pendingControls[name] = value;

    /// <summary>Queues a score line (e.g. <c>i 1 0 2 440</c>) for the running performance.</summary>
    /// <param name="scoreLine">Any real-time score statement; p2 is relative to the cycle that receives it.</param>
    public void SendEvent(string scoreLine) => pendingEvents.Enqueue(scoreLine);

    /// <summary>
    /// Queues a note that must start at the absolute score time <paramref name="atScoreTime"/>
    /// (seconds). The performance thread turns it into
    /// <c>i &lt;instrument&gt; &lt;at − now&gt; &lt;duration&gt; &lt;fields&gt;</c> right before the control
    /// cycle that receives it, so the start offset is exact no matter how long the event waited
    /// in the queue. Used by the piano roll and step sequencer scheduler (look-ahead scheduling).
    /// Events more than 0.25 s late are dropped (counted in <see cref="LateEvents"/>).
    /// </summary>
    /// <param name="atScoreTime">Absolute score time of the note start, seconds.</param>
    /// <param name="instrument">p1 token (<c>1</c> or <c>"Voice"</c>).</param>
    /// <param name="duration">p3, seconds.</param>
    /// <param name="fields">p4 and beyond, already formatted.</param>
    public void SendEventAt(double atScoreTime, string instrument, double duration, string fields) =>
        pendingTimed.Enqueue(new TimedEvent(atScoreTime, instrument, duration, fields));

    /// <summary>
    /// Queues orchestra code (typically one complete <c>instr ... endin</c> block) to be compiled
    /// into the running performance. Used for live coding when a literal is dragged in the editor.
    /// Only the most recent pending request is kept, older ones are dropped.
    /// </summary>
    /// <param name="orc">Orchestra text; redefining an existing instrument replaces it for new notes.</param>
    public void CompileOrc(string orc)
    {
        // Drain-then-enqueue is not atomic: two concurrent callers could leave two entries. Harmless,
        // because only the UI thread calls this and Step compiles at most one entry per cycle.
        while (pendingOrc.TryDequeue(out _)) { }
        pendingOrc.Enqueue(orc);
    }

    /// <summary>Asks the performance thread to capture every existing function table (see <see cref="TablesCaptured"/>).</summary>
    public void RequestTables() => tablesRequested = true;

    /// <summary>Copies the peak of each channel since the previous call into <paramref name="dest"/>, then resets them.</summary>
    /// <param name="dest">Receives one linear peak (1.0 = 0 dBFS) per channel.</param>
    /// <returns>The number of channels written.</returns>
    /// <remarks>
    /// Called by the UI thread every frame. Read-then-reset races with <see cref="AnalyseBlock"/>
    /// on the performance thread, so a peak written between the two can be lost; for a meter that
    /// refreshes 60 times a second this is invisible, and it keeps the audio path lock-free.
    /// </remarks>
    public int TakePeaks(Span<float> dest)
    {
        int n = Math.Min(OutputChannels, Math.Min(dest.Length, MaxChannels));
        for (int i = 0; i < n; i++)
        {
            dest[i] = peaks[i];
            peaks[i] = 0;
        }
        return n;
    }

    /// <summary>Copies the oscilloscope buffer in chronological order (most recent sample last).</summary>
    /// <param name="dest">Array of at least <see cref="ScopeSize"/> elements.</param>
    public void CopyScope(float[] dest)
    {
        // The write index points at the oldest sample, so reading from it forwards (wrapping)
        // yields oldest → newest. The performance thread may overwrite a few samples meanwhile.
        int start = Volatile.Read(ref scopeWrite);
        for (int i = 0; i < ScopeSize; i++)
            dest[i] = scope[(start + i) % ScopeSize];
    }

    /// <summary>Body of the performance thread: create, configure, compile, perform, destroy.</summary>
    /// <param name="job">The job passed to <see cref="Start"/>.</param>
    /// <remarks>
    /// Order matters: (1) open the app's WASAPI device first, because its rate becomes
    /// <c>--sample-rate</c>; (2) <c>csoundCreate</c> and register the instance for the static
    /// callbacks; (3) host audio / host MIDI hooks, which must be installed before compiling;
    /// (4) options, then <c>csoundCompileCSD</c> and <c>csoundStart</c>; (5) one of the two loops;
    /// (6) in <c>finally</c>, release devices, restore the GC mode and MMCSS, destroy the instance and
    /// raise <see cref="Finished"/> (always, even after an exception).
    /// </remarks>
    void Run(EngineJob job)
    {
        int result = -1;
        IntPtr cs = IntPtr.Zero;
        WasapiOutput? output = null;
        IntPtr mmcss = IntPtr.Zero;
        var previousGcMode = System.Runtime.GCSettings.LatencyMode;
        try
        {
            var options = job.Options.ToList();
            if (job.HostAudio is { } host)
            {
                // Open the device first: its sample rate decides the orchestra's sr.
                try
                {
                    output = WasapiOutput.Open(host.DeviceId, host.Mode, host.Preset);
                }
                catch (Exception ex) when (host.DeviceId is not null)
                {
                    // The chosen output is unplugged, disabled or busy: fall back to the Windows
                    // default output instead of failing (the saved choice is not changed).
                    Post(Loc.S($"⚠ La salida elegida no está disponible ({ex.Message}). Se usa la salida predeterminada de Windows.",
                               $"⚠ The chosen output is not available ({ex.Message}). Using the Windows default output."), MessageKind.Warning);
                    output = WasapiOutput.Open(null, host.Mode, host.Preset);
                }
                // Register this thread with the Multimedia Class Scheduler («Pro Audio» task) so
                // Windows boosts its priority while it feeds the device; reverted in finally.
                uint taskIndex = 0;
                mmcss = WasapiInterop.AvSetMmThreadCharacteristicsW("Pro Audio", ref taskIndex);
                AudioDescription = output.Description;
                NoteOutputLatency(output);
                Post("🔊 " + output.Description, MessageKind.Info);
                if (output.Hint is { } hint)
                    Post("💡 " + hint, MessageKind.Warning);
                options.Add("--sample-rate=" + output.SampleRate);
                // Avoid long blocking garbage collections while short audio periods are running.
                System.Runtime.GCSettings.LatencyMode = System.Runtime.GCLatencyMode.SustainedLowLatency;

                // Live input. A failure here never stops the performance: Csound's `in` then reads
                // silence. nchnls_i is NOT forced: Csound defaults it to nchnls (or the orchestra's
                // own nchnls_i), and forcing 2 would break mono orchestras that use `ain in`. The
                // capture channels are mapped onto whatever Csound expects (see AdaptiveInputReader).
                if (host.Input is { } inSettings)
                {
                    try
                    {
                        input = inSettings.Loopback
                            ? WasapiInput.OpenLoopback(inSettings.DeviceId)
                            : WasapiInput.Open(inSettings.DeviceId, host.Preset);
                        Post("🎙 " + input.Description, MessageKind.Info);
                    }
                    catch (Exception ex)
                    {
                        // The Windows default input (DeviceId null) is the normal setting, and with
                        // the microphone disabled in Windows it fails on EVERY play: say it once per
                        // session then. A device the user chose by name is reported every time.
                        if (inSettings.DeviceId is not null || !defaultInputFailureReported)
                            Post(Loc.S("⚠ Sin entrada de audio: ", "⚠ No audio input: ") + ex.Message
                                 + (inSettings.DeviceId is null ? Loc.S(" (se toca sin entrada; este aviso no se repetirá en esta sesión)", " (playing without input; this notice will not repeat this session)") : ""),
                                 MessageKind.Warning);
                        if (inSettings.DeviceId is null) defaultInputFailureReported = true;
                        input = null;
                    }
                }
            }

            // Csound will drive the device itself: read the device's Windows rate now, before
            // the device is opened, so the COM enumeration cannot delay the first audio buffers.
            int csoundDeviceRate = job.CsoundDevice is { } deviceLabel && !deviceLabel.Contains("ASIO", StringComparison.OrdinalIgnoreCase)
                ? WasapiOutput.FindMixRateByName(deviceLabel.Length == 0 ? null : deviceLabel)
                : 0;

            cs = CsoundNative.csoundCreate(IntPtr.Zero, CsoundLocator.PluginsDir);
            if (cs == IntPtr.Zero)
                throw new InvalidOperationException(Loc.S("csoundCreate devolvió NULL.", "csoundCreate returned NULL."));

            // The native callbacks are static (UnmanagedCallersOnly cannot capture `this`): they find
            // their engine through this map, keyed by the CSOUND* they receive.
            Instances[cs] = this;
            CsoundNative.csoundSetMessageStringCallback(cs, &OnMessage);
            // Host audio: Csound opens no device and leaves spin/spout to us (PerformHost).
            if (output is not null)
                CsoundNative.csoundSetHostAudioIO(cs);

            midi = job.Midi;
            if (midi is not null)
            {
                // MIDI comes from the app's MidiHub: ports, on-screen keyboard, MIDI learn…
                midi.ClearCsoundQueue();
                CsoundNative.csoundSetHostMIDIIO(cs);
                CsoundNative.csoundSetExternalMidiInOpenCallback(cs, &OnMidiOpen);
                CsoundNative.csoundSetExternalMidiReadCallback(cs, &OnMidiRead);
                CsoundNative.csoundSetExternalMidiInCloseCallback(cs, &OnMidiClose);
                // Csound only calls the MIDI-in callbacks when a MIDI input device is enabled; the
                // device number is irrelevant with host MIDI I/O.
                options.Add("-M0");
            }

            // Relative sample/file names in the orchestra are resolved against the CSD's folder.
            // Note: the current directory is PROCESS-wide and is not restored after the run.
            if (job.WorkingDirectory is not null && Directory.Exists(job.WorkingDirectory))
                Directory.SetCurrentDirectory(job.WorkingDirectory);

            // One call with every option: Csound 7 splits the string itself (see EngineJob.Options).
            if (options.Count > 0)
                CsoundNative.csoundSetOption(cs, string.Join(' ', options));

            // mode 1 = the argument is the CSD text itself; async 0 = compile now, synchronously.
            result = CsoundNative.csoundCompileCSD(cs, job.CsdText, 1, 0);
            if (result == 0 && job.LiveValues)
            {
                var monitor = new LiveValueMonitor();
                if (monitor.Attach(cs, job.InstrumentNames ?? []))
                    Live = monitor;
            }
            // Breakpoints share the debugger with the live values (see CsoundEngine.Debugger.cs).
            if (result == 0)
                AttachBreakpoints(cs, job, appAudioEngine: output is not null);
            else
                Breakpoints = null;
            if (result == 0)
                result = CsoundNative.csoundStart(cs);

            if (result == 0 && output is not null)
                PerformHost(cs, output, ref result);
            else if (result == 0)
                Perform(cs, ref result, job.CsoundDevice, csoundDeviceRate);
            else
                Post(Loc.S($"La compilación falló (código {result}).", $"Compilation failed (code {result})."), MessageKind.Error);
        }
        catch (Exception ex)
        {
            Post(ex.Message, MessageKind.Error);
        }
        finally
        {
            // Unpublish the reader first so the UI stops reading input statistics/peaks, then
            // close the devices (capture before render).
            Volatile.Write(ref inputReader, null);
            input?.Dispose();
            input = null;
            output?.Dispose();
            System.Runtime.GCSettings.LatencyMode = previousGcMode;
            if (mmcss != IntPtr.Zero)
                WasapiInterop.AvRevertMmThreadCharacteristics(mmcss);
            if (cs != IntPtr.Zero)
            {
                DetachBreakpoints(cs);
                Live?.Detach(cs);
                // Destroy before unregistering so the shutdown messages still reach the console.
                CsoundNative.csoundDestroy(cs);
                Instances.TryRemove(cs, out _);
            }
            FlushPartialLine();
            // Meters and scope fall to zero instead of freezing on the last block.
            Array.Clear(peaks);
            Array.Clear(scope);
            // Still on the performance thread: subscribers must marshal to the UI thread themselves.
            Finished?.Invoke(result);
        }
    }

    /// <summary>Reads the stream properties after <c>csoundStart</c> and prints the start banner.</summary>
    /// <param name="cs">The started Csound instance (performance thread).</param>
    /// <remarks>
    /// sr, ksmps, nchnls, nchnls_i and 0dbfs are only final after <c>csoundStart</c> (the orchestra
    /// header and options decide them), so every per-run size is derived here.
    /// </remarks>
    void BeginPerformance(IntPtr cs)
    {
        SampleRate = CsoundNative.csoundGetSr(cs);
        Ksmps = (int)CsoundNative.csoundGetKsmps(cs);
        OutputChannels = (int)CsoundNative.csoundGetChannels(cs, 0);
        InputChannels = (int)CsoundNative.csoundGetChannels(cs, 1);
        // Orchestras without `0dbfs = 1` use Csound's legacy 32768; meters, scope, recorder and the
        // device all work in ±1.0, so everything leaving spout is multiplied by 1/0dbfs.
        double zeroDb = CsoundNative.csoundGet0dBFS(cs);
        zeroDbfs = zeroDb > 0 ? zeroDb : 1.0;
        scale = (float)(1.0 / zeroDbfs);
        autoTablesDone = false;
        // Live values are sampled per control cycle: kr = sr / ksmps cycles per second.
        Live?.Configure(SampleRate / Math.Max(1, Ksmps), Ksmps);
        Post($"▶ sr = {SampleRate:0}  ·  ksmps = {Ksmps}  ·  nchnls = {OutputChannels}  ·  0dbfs = {zeroDb:0.###}", MessageKind.Info);
    }

    /// <summary>1 / 0dbfs: converts Csound sample values to ±1.0 full scale.</summary>
    float scale = 1;

    /// <summary>True once the automatic table capture after start has happened.</summary>
    bool autoTablesDone;

    /// <summary>
    /// One control cycle: apply pending UI requests, perform <c>ksmps</c> frames, analyse the
    /// output for meters/scope and publish the score time. Shared by both audio paths.
    /// </summary>
    /// <param name="cs">The running Csound instance.</param>
    /// <returns>The <c>csoundPerformKsmps</c> result: 0 = continue, &gt;0 = score finished, &lt;0 = error.</returns>
    /// <remarks>
    /// Runs on the performance thread only. Order within one cycle: control channels → cycle hook →
    /// queued invokes → score lines → timed notes → live orchestra code → live input into spin →
    /// <c>csoundPerformKsmps</c> → inserts, meters, scope, recorder → score time → table capture.
    /// Everything before <c>csoundPerformKsmps</c> is therefore visible to the instruments in the
    /// very cycle that follows.
    /// </remarks>
    int Step(IntPtr cs)
    {
        // Keys is a snapshot; TryRemove takes each value atomically, so a value written by the UI
        // after the snapshot simply waits for the next cycle.
        foreach (var key in pendingControls.Keys)
            if (pendingControls.TryRemove(key, out double v))
                CsoundNative.csoundSetControlChannel(cs, key, v);
        RunCycleHook(cs); // e.g. Ableton Link's LINK_* channels (Engine/CsoundEngine.CycleHook.cs)
        if (!pendingInvokes.IsEmpty && !IsPausedAtBreakpoint)
            RunInvokes(cs); // e.g. Paint Rooms table uploads (Engine/CsoundEngine.Invoke.cs)
        while (pendingEvents.TryDequeue(out var ev))
            CsoundNative.csoundEventString(cs, ev, 0);
        if (!pendingTimed.IsEmpty)
        {
            // Real-time i statements take p2 as an offset from "now" (the start of the next
            // control cycle), so the absolute time is converted here, at the last moment.
            double cycleStart = CsoundNative.csoundGetScoreTime(cs);
            while (pendingTimed.TryDequeue(out var te))
            {
                double offset = te.At - cycleStart;
                if (offset < -MaxEventLateness)
                {
                    Interlocked.Increment(ref lateEvents);
                    continue;
                }
                // Slightly late (≤ MaxEventLateness) notes start now rather than being lost. Numbers
                // are formatted invariantly: a comma decimal separator would split p-fields.
                var ci = System.Globalization.CultureInfo.InvariantCulture;
                CsoundNative.csoundEventString(cs,
                    "i " + te.Instrument + " " + Math.Max(0, offset).ToString("0.#########", ci) + " " +
                    te.Duration.ToString("0.#########", ci) + " " + te.Fields, 0);
            }
        }
        // Never recompile while an instance is stopped mid-cycle at a breakpoint.
        if (!IsPausedAtBreakpoint && pendingOrc.TryDequeue(out var orc))
            CsoundNative.csoundCompileOrc(cs, orc, 0);

        // Live input: one control block of captured audio into spin. Csound does not clear spin,
        // so it is rewritten every cycle (silence while the input is stalled).
        if (inputReader is { } reader && InputChannels > 0)
        {
            double* spin = CsoundNative.csoundGetSpin(cs);
            if (spin is not null)
                reader.Read(spin, Ksmps, InputChannels, zeroDbfs, Stopwatch.GetTimestamp(), InputRouting);
        }

        // Computes ksmps frames into spout. With Csound's own I/O this call also blocks on the device.
        DebugBeforeCycle(cs);
        int r = CsoundNative.csoundPerformKsmps(cs);
        DebugAfterCycle();
        if (cycleWithoutAudio)
            return r; // stopped at a breakpoint: spout holds no complete cycle (CsoundEngine.Debugger.cs)

        // spout = ksmps interleaved frames of nchnls doubles, in Csound units (±0dbfs).
        double* spout = CsoundNative.csoundGetSpout(cs);
        if (spout is not null && OutputChannels > 0)
        {
            ApplyInserts(spout); // VST3 insert chain (app WASAPI engine only), CsoundEngine.Inserts.cs
            AnalyseBlock(spout, OutputChannels, Math.Min(OutputChannels, MaxChannels), scale);
            Volatile.Read(ref recorder)?.Push(spout, Ksmps * OutputChannels, scale);
        }

        double now = CsoundNative.csoundGetScoreTime(cs);
        Volatile.Write(ref scoreTime, now);

        // Capture tables once automatically shortly after start (score f-statements and ftgen
        // in the header have run by then), and again whenever the UI asks for it.
        if (tablesRequested || (!autoTablesDone && now >= 0.2))
        {
            autoTablesDone = true;
            tablesRequested = false;
            TablesCaptured?.Invoke(CaptureTables(cs));
        }
        return r;
    }

    /// <summary>Loop used when Csound drives the audio device itself (PortAudio/ASIO, Csound WASAPI) or renders offline.</summary>
    /// <param name="cs">The started Csound instance.</param>
    /// <param name="result">Receives 0 when the score ended normally, or Csound's negative error code.</param>
    /// <param name="csoundDevice">Device label for the banner (<see cref="EngineJob.CsoundDevice"/>), or <c>null</c> (offline).</param>
    /// <param name="csoundDeviceRate">The device's Windows mix rate read before opening it, 0 = unknown.</param>
    /// <remarks>
    /// Pacing comes from Csound itself: its real-time module blocks inside <c>csoundPerformKsmps</c>
    /// until the device accepts the block; an offline render simply runs as fast as the CPU allows.
    /// The insert chain is not available on this path (<c>SkipInserts</c> reports that).
    /// </remarks>
    void Perform(IntPtr cs, ref int result, string? csoundDevice, int csoundDeviceRate)
    {
        BeginPerformance(cs);
        SkipInserts();
        if (csoundDevice is not null)
            DescribeCsoundDevice(csoundDevice, csoundDeviceRate);
        while (!stopRequested)
        {
            int r = Step(cs);
            if (r != 0)
            {
                result = r > 0 ? 0 : r;
                break;
            }
        }
    }

    /// <summary>True once a failure to open the Windows DEFAULT input was reported (see PerformHost).</summary>
    static bool defaultInputFailureReported;

    /// <summary>
    /// Seconds the output device may go without having room for new samples before the run is
    /// ended as «device stalled» (a running device frees a period every few ms; 2 s is far beyond
    /// any normal hiccup, short enough that the user is not left with a silent, locked app).
    /// </summary>
    const double StalledDeviceSeconds = 2.0;

    /// <summary>
    /// Loop used with the application's own WASAPI output. The device's event wakes the thread;
    /// as many control cycles as needed are computed to fill the frames the device asks for, and
    /// the samples are written in the device format.
    /// </summary>
    /// <remarks>
    /// Csound's channels are mapped to the device's: mono is duplicated to every channel, extra
    /// Csound channels beyond the device's are dropped, missing ones are silent. On stop, a
    /// short linear fade-out avoids a click. Dropouts and DSP load are measured per period.
    /// <para>
    /// Csound computes in blocks of ksmps frames while the device asks for arbitrary frame counts
    /// (its period, or whatever is free in its buffer), so a FIFO of float frames in the DEVICE
    /// channel layout sits between them: <c>Produce</c> appends whole Csound blocks until enough
    /// frames are queued, <c>Emit</c> hands exactly the requested frames to the device and keeps
    /// the leftover (less than one block) for the next period.
    /// </para>
    /// </remarks>
    /// <param name="cs">The started Csound instance (opened with host audio I/O).</param>
    /// <param name="output">The opened, not yet started, WASAPI render stream.</param>
    /// <param name="result">Receives 0 when the score ended normally, or Csound's negative error code.</param>
    void PerformHost(IntPtr cs, WasapiOutput output, ref int result)
    {
        BeginPerformance(cs);
        AudioDescription = output.Description + " · " + RateSummary(output.MixRate, output.SampleRate);
        Post("🔊 " + RateSummary(output.MixRate, output.SampleRate), MessageKind.Info);
        StartInput(output);
        PrepareInserts();
        int devCh = output.Channels, csCh = OutputChannels;
        // Capacity: a full device buffer plus two Csound blocks of overshoot; grown on demand below.
        var fifo = new float[(output.BufferFrames + Ksmps * 2) * devCh];
        int fifoFrames = 0;
        bool finished = false;
        int runResult = 0;
        double ticksToSeconds = 1.0 / Stopwatch.Frequency;

        // Pull Csound blocks until the FIFO holds at least `frames` frames (or the score ended).
        void Produce(int frames)
        {
            while (fifoFrames < frames && !finished)
            {
                int r = Step(cs);
                if (r != 0)
                {
                    runResult = r > 0 ? 0 : r;
                    finished = true;
                    break;
                }
                if (cycleWithoutAudio)
                {
                    // Stopped at a breakpoint: stop producing, Emit pads the period with silence
                    // so the device keeps running. A skipped hit is resumed by the next Step.
                    if (IsPausedAtBreakpoint) break;
                    continue;
                }
                double* spout = CsoundNative.csoundGetSpout(cs);
                if (spout is null) continue;
                if ((fifoFrames + Ksmps) * devCh > fifo.Length)
                    Array.Resize(ref fifo, (fifoFrames + Ksmps) * devCh * 2);
                // Remap Csound channels → device channels and scale to ±1.0 float.
                for (int f = 0; f < Ksmps; f++)
                {
                    int dst = (fifoFrames + f) * devCh;
                    double* frame = spout + f * csCh;
                    for (int c = 0; c < devCh; c++)
                    {
                        double v = csCh == 1 ? frame[0] : c < csCh ? frame[c] : 0;
                        fifo[dst + c] = (float)(v * scale);
                    }
                }
                fifoFrames += Ksmps;
            }
        }

        // Write `frames` frames from the FIFO (zero-padded) and shift the remainder down.
        void Emit(int frames, bool fadeOut)
        {
            if (frames * devCh > fifo.Length)
                Array.Resize(ref fifo, frames * devCh);
            int available = Math.Min(frames, fifoFrames);
            if (available < frames)
                Array.Clear(fifo, available * devCh, (frames - available) * devCh);
            if (fadeOut)
                for (int f = 0; f < frames; f++)
                {
                    float g = 1f - (float)f / frames;
                    for (int c = 0; c < devCh; c++) fifo[f * devCh + c] *= g;
                }
            output.Write(fifo, frames);
            int remaining = fifoFrames - available;
            if (remaining > 0)
                Array.Copy(fifo, available * devCh, fifo, 0, remaining * devCh);
            fifoFrames = remaining;
        }

        // Pre-fill the whole buffer before starting so the first period is not a dropout.
        int initial = output.FramesWritable(out _);
        Produce(initial);
        Emit(initial, false);
        output.Start();

        // A wake-up much later than one period means the thread was held up: count it as a dropout.
        double periodSeconds = (double)output.PeriodFrames / output.SampleRate;
        long lastWake = Stopwatch.GetTimestamp();
        // Last wake-up at which the device had room for samples (stalled-device watchdog below).
        long lastProgress = lastWake;
        int wakes = 0;

        // Event-driven loop: one iteration per device wake-up (normally once per period).
        while (true)
        {
            if (!output.Wait(2000))
            {
                Post(Loc.S("El dispositivo de audio dejó de pedir muestras (¿se desconectó?).", "The audio device stopped requesting samples (was it disconnected?)."), MessageKind.Warning);
                break;
            }
            long wake = Stopwatch.GetTimestamp();
            double gap = (wake - lastWake) * ticksToSeconds;
            lastWake = wake;
            // The first ~20 wake-ups are ignored: stream start-up (and the pre-fill) produces
            // irregular gaps that are not real dropouts. A gap above ~2 periods (+1 ms jitter
            // allowance) means at least one period was missed.
            if (++wakes > 20)
            {
                if (gap * 1000 > Volatile.Read(ref worstWakeMs))
                    Volatile.Write(ref worstWakeMs, gap * 1000);
                if (gap > periodSeconds * 1.9 + 0.001)
                    Interlocked.Increment(ref underruns);
            }
            int need = output.FramesWritable(out bool underrun);
            if (underrun)
                Interlocked.Increment(ref underruns);
            if (!inputErrorReported && input?.Error is { } inputError)
            {
                inputErrorReported = true;
                Post("⚠ " + inputError, MessageKind.Warning);
            }
            if (need > 0)
                lastProgress = wake;
            if (need <= 0)
            {
                // The device woke us but has no room: normal for a moment. Two failure cases must
                // still end the run, otherwise the app would sit «playing» in silence with the
                // audio settings disabled (seen with a UR22mkII whose driver stopped consuming):
                //  * Stop pressed — honour it even though no buffer space ever appears;
                //  * no room for StalledDeviceSeconds — the device clock has stopped.
                if (stopRequested)
                    break;
                if ((wake - lastProgress) * ticksToSeconds > StalledDeviceSeconds)
                {
                    Post(Loc.S("La tarjeta de audio dejó de pedir muestras (su reloj se detuvo). Desconecta y vuelve a conectar la interfaz, o elige otra salida en Configuración › Audio.",
                               "The audio device stopped consuming samples (its clock stopped). Unplug and reconnect the interface, or choose another output in Settings › Audio."), MessageKind.Error);
                    runResult = -1;
                    LastRunOutputStalled = true;
                    break;
                }
                continue;
            }

            if (stopRequested)
            {
                // Graceful stop: one last period faded from full level to silence, then one period
                // of pure silence (fifoFrames = 0 makes Emit zero-pad) so the device does not replay
                // stale buffer contents, then a short wait for it to play out.
                Produce(need);
                Emit(need, fadeOut: true);
                if (output.Wait(500) && output.FramesWritable(out _) is var tail and > 0)
                {
                    fifoFrames = 0;
                    Emit(tail, false);
                }
                output.Wait(200);
                break;
            }

            // DSP load = compute time / audio time produced. Smoothed with a one-pole average
            // (α = 0.1, ≈ 10 periods). Taking longer than the audio itself lasts is a dropout,
            // except while paused at a breakpoint (the wait is intentional).
            long t0 = Stopwatch.GetTimestamp();
            Produce(need);
            double spent = (Stopwatch.GetTimestamp() - t0) * ticksToSeconds;
            double budget = (double)need / output.SampleRate;
            double previous = Volatile.Read(ref dspLoad);
            double load = spent / budget;
            Volatile.Write(ref dspLoad, previous < 0 ? load : previous * 0.9 + load * 0.1);
            if (spent > budget && !IsPausedAtBreakpoint)
                Interlocked.Increment(ref underruns);

            Emit(need, false);
            if (finished && fifoFrames == 0)
            {
                // Let the last buffer play out before closing the device.
                Thread.Sleep((int)(1000.0 * output.BufferFrames / output.SampleRate) + 20);
                break;
            }
        }
        result = runResult;
    }

    /// <summary>
    /// "device 44100 Hz · Csound sr 48000 Hz" with a note when they differ, so a .csd that says
    /// 48000 on a 44.1 kHz device is not confusing.
    /// </summary>
    /// <param name="deviceRate">The device's Windows mix rate (Sound panel / driver panel), 0 if unknown.</param>
    /// <param name="streamRate">Rate of the stream the app opened (app WASAPI engine), 0 when Csound drives the device.</param>
    /// <param name="windowsConverts">True when Windows resamples Csound's output to the device rate (shared-mode APIs).</param>
    /// <returns>A localised one-line summary for the console and <see cref="AudioDescription"/>.</returns>
    /// <remarks>
    /// When the rates differ, the note explains who reconciles them: Windows' shared-mode resampler,
    /// an exclusive stream opened at Csound's rate, or nobody (a real mismatch — pitch/speed errors).
    /// </remarks>
    string RateSummary(int deviceRate, int streamRate, bool windowsConverts = false)
    {
        string device = deviceRate > 0 ? $"{deviceRate} Hz" : "?";
        string note = "";
        if (deviceRate > 0 && Math.Abs(deviceRate - SampleRate) > 0.5)
            note = windowsConverts
                ? Loc.S(" (Windows convierte)", " (Windows converts)")
                : streamRate > 0 && Math.Abs(streamRate - SampleRate) < 0.5
                    ? Loc.S($" (stream exclusivo a {streamRate} Hz)", $" (exclusive stream at {streamRate} Hz)")
                    : Loc.S(" (¡no coinciden!)", " (mismatch!)");
        return Loc.S($"dispositivo {device} · Csound sr {SampleRate:0} Hz{note}", $"device {device} · Csound sr {SampleRate:0} Hz{note}");
    }

    /// <summary>
    /// Csound drives the device (PortAudio, Csound WASAPI…): report the device's Windows mix rate
    /// next to Csound's sr. ASIO drivers switch to Csound's rate, so no Windows rate applies to them.
    /// </summary>
    /// <param name="label">Device label from the job (empty = module default).</param>
    /// <param name="rate">The device's Windows mix rate, read before the device was opened (0 = unknown).</param>
    void DescribeCsoundDevice(string label, int rate)
    {
        string name = label.Length == 0 ? Loc.S("dispositivo predeterminado", "default device") : label;
        if (label.Contains("ASIO", StringComparison.OrdinalIgnoreCase))
        {
            AudioDescription = Loc.S($"{name} · Csound sr {SampleRate:0} Hz (el driver ASIO sigue a Csound)",
                                     $"{name} · Csound sr {SampleRate:0} Hz (the ASIO driver follows Csound)");
        }
        else
        {
            AudioDescription = name + " · " + RateSummary(rate, 0, windowsConverts: true);
        }
        Post("🔊 " + AudioDescription, MessageKind.Info);
    }

    /// <summary>
    /// Creates the input reader (resampler + drift control) and starts the capture thread, once
    /// Csound's sr, ksmps and nchnls_i are known. On failure the run continues without input.
    /// </summary>
    /// <param name="output">The render stream; its period sizes the input buffer target.</param>
    void StartInput(WasapiOutput output)
    {
        if (input is null)
            return;
        if (InputChannels <= 0)
        {
            Post(Loc.S("La orquesta no tiene canales de entrada (nchnls_i = 0): la entrada no se usa.",
                       "The orchestra has no input channels (nchnls_i = 0): the input is not used."), MessageKind.Warning);
            return;
        }
        // Target fill = one capture packet + one output burst and one control block (both in
        // input frames) + 3 ms of margin: just enough that the ring never runs dry between the
        // two threads' wake-ups. This is the latency the input adds on top of the devices' own.
        // ratio converts Csound frames (output side) into capture frames (input side).
        double ratio = input.SampleRate / SampleRate;
        int target = input.PeriodFrames + (int)Math.Ceiling((output.PeriodFrames + Ksmps) * ratio) + input.SampleRate * 3 / 1000;
        var reader = new AdaptiveInputReader(input.Ring, input.SampleRate, SampleRate, target, (int)(output.PeriodFrames * ratio));
        try
        {
            input.Start();
        }
        catch (Exception ex)
        {
            Post(Loc.S("⚠ Sin entrada de audio: ", "⚠ No audio input: ") + ex.Message, MessageKind.Warning);
            return;
        }
        // Publishing the reader is what makes Step start feeding spin (and HasLiveInput true).
        Volatile.Write(ref inputReader, reader);
        string conversion = reader.Resampling
            ? Loc.S($"remuestreo {input.SampleRate} → {SampleRate:0} Hz", $"resampling {input.SampleRate} → {SampleRate:0} Hz")
            : Loc.S("misma frecuencia", "same rate");
        string mapping = input.Channels == 1 && InputChannels > 1
            ? Loc.S($"mono a los {InputChannels} canales", $"mono to all {InputChannels} channels")
            : InputRouting switch
            {
                Audio.InputRouting.Input1 => Loc.S("entrada 1 a todos los canales", "input 1 to all channels"),
                Audio.InputRouting.Input2 => Loc.S("entrada 2 a todos los canales", "input 2 to all channels"),
                Audio.InputRouting.Sum => Loc.S("entradas sumadas a todos los canales", "inputs summed to all channels"),
                _ => $"{input.Channels} ch → nchnls_i {InputChannels}",
            };
        Post(Loc.S($"🎙 Entrada → Csound: {conversion} · {mapping} · búfer {1000.0 * reader.TargetFrames / input.SampleRate:0.#} ms con corrección de deriva",
                   $"🎙 Input → Csound: {conversion} · {mapping} · buffer {1000.0 * reader.TargetFrames / input.SampleRate:0.#} ms with drift correction"),
             MessageKind.Info);
        AudioDescription += "\n" + input.Description + " · " + conversion;
    }

    /// <summary>Updates the peak meters and appends the mono mix of the block to the scope ring buffer.</summary>
    /// <param name="spout">Csound's output buffer: <see cref="Ksmps"/> interleaved frames of <paramref name="nch"/> samples.</param>
    /// <param name="nch">Channels per frame in <paramref name="spout"/> (Csound's nchnls).</param>
    /// <param name="meterChannels">How many of those channels are metered (at most <see cref="MaxChannels"/>).</param>
    /// <param name="scale">1 / 0dbfs, to read samples as ±1.0 full scale (shadows the field on purpose).</param>
    /// <remarks>
    /// The scope shows (ch1 + ch2) / 2 for multichannel output — channels beyond 2 are not mixed in.
    /// The write index is published once per block with a volatile write so <see cref="CopyScope"/>
    /// never sees an index ahead of the samples it covers.
    /// </remarks>
    void AnalyseBlock(double* spout, int nch, int meterChannels, float scale)
    {
        int w = scopeWrite;
        for (int f = 0; f < Ksmps; f++)
        {
            double* frame = spout + f * nch;
            for (int c = 0; c < meterChannels; c++)
            {
                float a = MathF.Abs((float)frame[c] * scale);
                if (a > peaks[c]) peaks[c] = a;
            }
            float mono = nch > 1 ? (float)(frame[0] + frame[1]) * 0.5f : (float)frame[0];
            scope[w] = mono * scale;
            w = (w + 1) % ScopeSize;
        }
        Volatile.Write(ref scopeWrite, w);
    }

    /// <summary>Copies every existing table (numbers 1..<see cref="MaxTableNumber"/>), decimating long ones.</summary>
    /// <param name="cs">The running Csound instance (performance thread, between cycles).</param>
    /// <returns>One snapshot per existing table, in ascending table number.</returns>
    /// <remarks>
    /// Runs inside the audio loop: the min/max scan reads every point of every table, so very large
    /// tables (long samples loaded with GEN01) cost time in that cycle. Decimation is plain point
    /// picking (index i·len/points), not averaging — good enough for a thumbnail.
    /// </remarks>
    static List<TableSnapshot> CaptureTables(IntPtr cs)
    {
        var tables = new List<TableSnapshot>();
        for (int n = 1; n <= MaxTableNumber; n++)
        {
            if (CsoundNative.csoundTableLength(cs, n) <= 0)
                continue;
            double* data;
            int len = CsoundNative.csoundGetTable(cs, &data, n);
            if (len <= 0 || data is null)
                continue;

            double min = double.MaxValue, max = double.MinValue;
            for (int i = 0; i < len; i++)
            {
                if (data[i] < min) min = data[i];
                if (data[i] > max) max = data[i];
            }
            int points = Math.Min(len, TablePoints);
            var values = new float[points];
            for (int i = 0; i < points; i++)
                values[i] = (float)data[(long)i * len / points];
            tables.Add(new TableSnapshot(n, len, values, min, max));
        }
        return tables;
    }

