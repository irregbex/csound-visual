// Stft.cs — Paint Rooms foundation (spectral analysis helpers).
//
// Role: a small, dependency-free toolkit for the rooms that go from SOUND to IMAGE and back:
//   * Fft            — in-place radix-2 complex FFT (forward and inverse), any power-of-two size;
//   * WindowFunction — analysis windows (Hann, Hamming, Blackman, Blackman–Harris, rectangular);
//   * Stft           — short-time Fourier transform: Forward (signal → frames of complex bins),
//                      Inverse (frames → signal by weighted overlap-add, exact reconstruction with
//                      any window at hop ≤ frame/2), magnitudes, bin frequencies and the
//                      phase-vocoder «true frequency» of a bin from the phase advance between frames.
//
// Conventions: frames are centred (frame m covers samples m·hop − N/2 … m·hop + N/2 − 1, the signal
// being zero-padded at both ends), bins 0 … N/2 (DC … Nyquist) for real signals, magnitudes
// normalised so a full-scale sine reads ≈ 1.0 at its bin with the window's coherent gain removed.
//
// Status: Forward/Inverse are unit-tested (round-trip error < 1e-9 with Hann at 75 % overlap).
// Who uses what: the «Spectrum Room» code (Paint/SpectralAnalysis.cs, Paint/SpectralMask.cs) runs
// its OWN streaming frame loops with the same frame convention — Stft.Forward keeps every complex
// frame in memory, far too much for minutes of audio — and only borrows Fft.Transform,
// WindowFunction and Stft.TrueFrequency from here. Forward / Inverse / Magnitudes remain as the
// reference implementation of the conventions (and for tests and short signals).
// Pure computation, thread-safe (no shared state).
//
// Units: signals are float samples (±1.0 full scale), sampleRate in Hz, sizes and hops in samples,
// bin k ↔ k·sr/N Hz, frame m ↔ m·hop/sr seconds, phases in radians.

using System.Numerics;

namespace CsoundVisual.Paint;

/// <summary>In-place iterative radix-2 FFT.</summary>
public static class Fft
{
    /// <summary>True when <paramref name="n"/> is a power of two (≥ 2).</summary>
    /// <param name="n">Candidate FFT size.</param>
    /// <returns><c>true</c> for 2, 4, 8, …; a power of two has exactly one bit set, so n &amp; (n − 1) clears it to 0.</returns>
    public static bool IsPowerOfTwo(int n) => n >= 2 && (n & (n - 1)) == 0;

    /// <summary>
    /// Transforms <paramref name="data"/> in place. Forward: X[k] = Σ x[n]·e^(−2πikn/N) (no
    /// scaling). Inverse: x[n] = (1/N)·Σ X[k]·e^(+2πikn/N) (scaled by 1/N, so Inverse(Forward(x)) = x).
    /// </summary>
    /// <param name="data">N complex values, N a power of two; replaced by their transform.</param>
    /// <param name="inverse">False = forward (e^−), true = inverse (e^+ and 1/N).</param>
    /// <remarks>
    /// Cooley–Tukey decimation in time: O(N log N), no allocations. Twiddle factors are generated by
    /// repeated multiplication (w *= wl) rather than a table, which is simple and accurate enough
    /// for the sizes used here (≤ 32768; rounding error grows only slowly with the stage length).
    /// </remarks>
    /// <exception cref="ArgumentException">The length is not a power of two.</exception>
    public static void Transform(Span<Complex> data, bool inverse = false)
    {
        int n = data.Length;
        if (!IsPowerOfTwo(n)) throw new ArgumentException("FFT size must be a power of two.");
        // Bit-reversal permutation: element i moves to the index whose binary digits are i's reversed,
        // so the butterflies below can work in place. j is the bit-reversed counter of i, updated
        // by a «reversed increment» (propagate the carry from the top bit downwards). Swapping only
        // when i < j performs each exchange once.
        for (int i = 1, j = 0; i < n; i++)
        {
            int bit = n >> 1;
            for (; (j & bit) != 0; bit >>= 1) j ^= bit;
            j ^= bit;
            if (i < j) (data[i], data[j]) = (data[j], data[i]);
        }
        // Butterflies: stages of length 2, 4, …, n. In each stage, every block of `len` values combines
        // its two halves (already transformed DFTs of length len/2): with w = e^(∓2πik/len),
        // X[k] = E[k] + w·O[k] and X[k + len/2] = E[k] − w·O[k].
        double sign = inverse ? 1 : -1;
        for (int len = 2; len <= n; len <<= 1)
        {
            double ang = sign * 2 * Math.PI / len;
            var wl = new Complex(Math.Cos(ang), Math.Sin(ang));
            int half = len >> 1;
            for (int i = 0; i < n; i += len)
            {
                var w = Complex.One;
                for (int k = 0; k < half; k++)
                {
                    var u = data[i + k];
                    var v = data[i + k + half] * w;
                    data[i + k] = u + v;
                    data[i + k + half] = u - v;
                    w *= wl;
                }
            }
        }
        if (inverse)
        {
            double inv = 1.0 / n;
            for (int i = 0; i < n; i++) data[i] *= inv;
        }
    }
}

/// <summary>Analysis window shapes.</summary>
public enum WindowKind
{
    /// <summary>Hann (raised cosine): the general-purpose default.</summary>
    Hann,
    /// <summary>Hamming: narrower main lobe, higher far side lobes.</summary>
    Hamming,
    /// <summary>Blackman: lower side lobes (−58 dB).</summary>
    Blackman,
    /// <summary>4-term Blackman–Harris: very low side lobes (−92 dB), wide main lobe.</summary>
    BlackmanHarris,
    /// <summary>No window (box).</summary>
    Rectangular,
}

/// <summary>Window generation.</summary>
public static class WindowFunction
{
    /// <summary>
    /// A <b>periodic</b> window of <paramref name="size"/> points (the form that overlap-adds to a
    /// constant: Hann at hop = size/2 or size/4 sums exactly flat).
    /// </summary>
    /// <param name="kind">Window shape.</param>
    /// <param name="size">Number of points (the FFT size).</param>
    /// <returns>A new array w[0 … size−1].</returns>
    /// <remarks>
    /// Periodic = the symmetric window of size+1 points without its last point: x = 2πi/size
    /// (not 2πi/(size−1)), so w[0] is the only zero of Hann and the window is exactly one period of
    /// its cosines — what makes overlap-add sums flat and the DFT of the window clean.
    /// </remarks>
    public static double[] Create(WindowKind kind, int size)
    {
        var w = new double[size];
        for (int i = 0; i < size; i++)
        {
            double x = 2 * Math.PI * i / size;
            w[i] = kind switch
            {
                WindowKind.Hann => 0.5 - 0.5 * Math.Cos(x),
                WindowKind.Hamming => 0.54 - 0.46 * Math.Cos(x),
                WindowKind.Blackman => 0.42 - 0.5 * Math.Cos(x) + 0.08 * Math.Cos(2 * x),
                WindowKind.BlackmanHarris => 0.35875 - 0.48829 * Math.Cos(x) + 0.14128 * Math.Cos(2 * x) - 0.01168 * Math.Cos(3 * x),
                _ => 1.0,
            };
        }
        return w;
    }

    /// <summary>Coherent gain (mean value) of a window: a sine of amplitude A shows A·N·gain/2 at its bin.</summary>
    /// <param name="window">The window values.</param>
    /// <returns>Σw / N: 0.5 for Hann, 0.54 Hamming, 0.42 Blackman, 0.359 Blackman–Harris, 1 rectangular.</returns>
    public static double CoherentGain(double[] window) => window.Average();
}

/// <summary>Frame size, hop and window of an STFT.</summary>
/// <param name="FrameSize">FFT size, a power of two (e.g. 2048).</param>
/// <param name="HopSize">Samples between frames (e.g. FrameSize/4).</param>
/// <param name="Window">Window shape.</param>
public sealed record StftSettings(int FrameSize = 2048, int HopSize = 512, WindowKind Window = WindowKind.Hann)
{
    /// <summary>Bins per frame for a real signal: FrameSize/2 + 1 (DC … Nyquist).</summary>
    public int Bins => FrameSize / 2 + 1;
}

/// <summary>Result of <see cref="Stft.Forward"/>: complex spectra of successive frames.</summary>
/// <param name="Settings">How it was computed.</param>
/// <param name="SampleRate">Sample rate of the analysed signal.</param>
/// <param name="SignalLength">Length of the analysed signal (samples), needed to invert.</param>
/// <param name="Frames">Frames[m][k]: bin k (0…N/2) of frame m (centred at sample m·hop).</param>
public sealed record StftResult(StftSettings Settings, double SampleRate, int SignalLength, Complex[][] Frames)
{
    /// <summary>Number of frames.</summary>
    public int FrameCount => Frames.Length;

    /// <summary>Centre frequency of bin <paramref name="k"/> in Hz: k·sr/N.</summary>
    /// <param name="k">Bin index, 0 … N/2.</param>
    /// <returns>Frequency in Hz (0 = DC, sr/2 = Nyquist).</returns>
    public double BinFrequency(int k) => k * SampleRate / Settings.FrameSize;

    /// <summary>Time of the centre of frame <paramref name="m"/> in seconds: m·hop/sr.</summary>
    /// <param name="m">Frame index.</param>
    /// <returns>Seconds from the start of the signal.</returns>
    public double FrameTime(int m) => m * Settings.HopSize / SampleRate;
}

/// <summary>Short-time Fourier transform (see the file header).</summary>
public static class Stft
{
    /// <summary>
    /// Analyses <paramref name="signal"/>: frames centred every hop samples (zero-padded at the
    /// ends), windowed, FFT'd; keeps bins 0…N/2.
    /// </summary>
    /// <param name="signal">Mono samples.</param>
    /// <param name="sampleRate">Sample rate in Hz (stored for frequency/time conversions).</param>
    /// <param name="s">Frame size, hop and window.</param>
    /// <returns>All frames in memory: about 8·N bytes per frame (N/2 + 1 complex doubles).</returns>
    /// <exception cref="ArgumentException">Invalid frame/hop sizes.</exception>
    public static StftResult Forward(ReadOnlySpan<float> signal, double sampleRate, StftSettings s)
    {
        int n = s.FrameSize, hop = s.HopSize;
        if (!Fft.IsPowerOfTwo(n) || hop < 1 || hop > n)
            throw new ArgumentException("FrameSize must be a power of two and 1 ≤ HopSize ≤ FrameSize.");
        var win = WindowFunction.Create(s.Window, n);
        // Frames centred on 0, hop, 2·hop, … up to the last sample: ⌊len/hop⌋ + 1 frames, so the
        // final samples are still covered by a frame centre (and the first half frame is zeros).
        int frames = signal.Length / hop + 1;
        var result = new Complex[frames][];
        var buf = new Complex[n];
        for (int m = 0; m < frames; m++)
        {
            int start = m * hop - n / 2;
            for (int i = 0; i < n; i++)
            {
                int j = start + i;
                // (uint) cast = one bounds check for both j < 0 and j ≥ length (zero padding).
                buf[i] = new Complex((uint)j < (uint)signal.Length ? signal[j] * win[i] : 0, 0);
            }
            Fft.Transform(buf);
            // A real input has a Hermitian spectrum (X[N−k] = conj X[k]): bins above N/2 are redundant.
            var bins = new Complex[s.Bins];
            Array.Copy(buf, bins, bins.Length);
            result[m] = bins;
        }
        return new StftResult(s, sampleRate, signal.Length, result);
    }

    /// <summary>
    /// Resynthesises a signal from (possibly modified) frames by weighted overlap-add: each frame is
    /// inverse-FFT'd (the negative-frequency half is rebuilt as the mirror conjugate, so the output
    /// is real), multiplied by the window again and added; the sum is divided by Σ window² at
    /// every sample. Exact for unmodified frames whenever the windows overlap (hop &lt; N).
    /// </summary>
    /// <param name="stft">Frames to resynthesise (same settings as the analysis).</param>
    /// <param name="length">Output length in samples; default = the analysed signal's length.</param>
    /// <returns>The real signal.</returns>
    /// <remarks>
    /// Why it is exact: frame m holds w·x around its centre; multiplying again by w and summing gives
    /// x·Σw² at every sample, and the division removes Σw² — for any window, not only those whose
    /// shifted sum is constant. For MODIFIED frames this is the least-squares (Griffin–Lim) estimate.
    /// Samples where Σw² ≈ 0 (no window covers them) are output as 0.
    /// </remarks>
    public static float[] Inverse(StftResult stft, int? length = null)
    {
        var s = stft.Settings;
        int n = s.FrameSize, hop = s.HopSize;
        int len = length ?? stft.SignalLength;
        var win = WindowFunction.Create(s.Window, n);
        var acc = new double[len];
        var norm = new double[len];
        var buf = new Complex[n];
        for (int m = 0; m < stft.FrameCount; m++)
        {
            var bins = stft.Frames[m];
            for (int k = 0; k < n; k++)
                buf[k] = k <= n / 2 ? bins[k] : Complex.Conjugate(bins[n - k]);
            // DC and Nyquist bins of a real signal are real.
            buf[0] = new Complex(buf[0].Real, 0);
            buf[n / 2] = new Complex(buf[n / 2].Real, 0);
            Fft.Transform(buf, inverse: true);
            int start = m * hop - n / 2;
            for (int i = 0; i < n; i++)
            {
                int j = start + i;
                if ((uint)j >= (uint)len) continue;
                acc[j] += buf[i].Real * win[i];
                norm[j] += win[i] * win[i];
            }
        }
        var y = new float[len];
        for (int i = 0; i < len; i++)
            y[i] = norm[i] > 1e-12 ? (float)(acc[i] / norm[i]) : 0f;
        return y;
    }

    /// <summary>
    /// Magnitudes of every frame (Frames × Bins), scaled so a sine of amplitude A reads ≈ A at its
    /// peak bin: |X| · 2 / (N · coherent gain).
    /// </summary>
    /// <param name="stft">The analysis.</param>
    /// <returns>mags[m][k], linear amplitude (1.0 = full-scale sine).</returns>
    /// <remarks>
    /// The factor 2 accounts for the energy in the discarded negative-frequency twin; it therefore
    /// over-reads DC and Nyquist (which have no twin) by 2×. A sine BETWEEN two bins reads lower
    /// (scalloping loss: up to −1.4 dB for Hann).
    /// </remarks>
    public static float[][] Magnitudes(StftResult stft)
    {
        int n = stft.Settings.FrameSize;
        double scale = 2.0 / (n * WindowFunction.CoherentGain(WindowFunction.Create(stft.Settings.Window, n)));
        var mags = new float[stft.FrameCount][];
        for (int m = 0; m < stft.FrameCount; m++)
        {
            var f = stft.Frames[m];
            var a = new float[f.Length];
            for (int k = 0; k < f.Length; k++) a[k] = (float)(f[k].Magnitude * scale);
            mags[m] = a;
        }
        return mags;
    }

    /// <summary>
    /// Phase-vocoder «true» frequency (Hz) of bin <paramref name="k"/> from its phases in two
    /// consecutive frames: the expected advance 2π·k·hop/N is removed, the remainder wrapped to
    /// (−π, π] is the deviation from the bin centre.
    /// </summary>
    /// <param name="previousPhase">Phase of bin k in frame m−1 (radians).</param>
    /// <param name="phase">Phase of bin k in frame m (radians).</param>
    /// <param name="k">Bin index.</param>
    /// <param name="s">Frame size and hop of the analysis.</param>
    /// <param name="sampleRate">Sample rate in Hz.</param>
    /// <returns>Estimated frequency of the component dominating bin k, in Hz.</returns>
    /// <remarks>
    /// A component at frequency f advances 2π·f·hop/sr radians per hop. The bin centre accounts for
    /// 2π·k·hop/N; the wrapped remainder δ gives the offset in bins δ·N / (2π·hop). Unambiguous only
    /// for offsets smaller than N / (2·hop) bins (±2 bins at 4× overlap — enough for a Hann lobe).
    /// </remarks>
    public static double TrueFrequency(double previousPhase, double phase, int k, StftSettings s, double sampleRate)
    {
        double expected = 2 * Math.PI * k * s.HopSize / s.FrameSize;
        double delta = phase - previousPhase - expected;
        // Principal value: subtract the nearest multiple of 2π (Math.Round uses banker's rounding at
        // exactly ±π, so the range is [−π, π] in practice — harmless).
        delta -= 2 * Math.PI * Math.Round(delta / (2 * Math.PI));
        return (k + delta * s.FrameSize / (2 * Math.PI * s.HopSize)) * sampleRate / s.FrameSize;
    }
}
