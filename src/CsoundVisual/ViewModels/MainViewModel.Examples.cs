using CommunityToolkit.Mvvm.Input;
using CsoundVisual.Localization;

namespace CsoundVisual.ViewModels;

/// <summary>
/// Example browser support and «follow what you open»: opening a file while Csound is playing
/// stops the old one and plays the new one.
/// </summary>
/// <remarks>
/// <para>
/// <b>Why a two-step switch.</b> The engine runs one performance at a time on its own thread and
/// stopping is asynchronous (fade-out, <c>csoundDestroy</c>, then the <c>Finished</c> event).
/// So switching never starts the new document directly: <see cref="SwitchPlaybackTo"/> records
/// it in <see cref="playAfterStop"/> and asks the engine to stop; when the main view model's
/// <c>OnFinished</c> handler runs (back on the UI thread) it calls
/// <see cref="StartQueuedPlayback"/>, which plays the queued document.
/// </para>
/// <para>
/// The browser window itself is <c>Views/ExamplesWindow.cs</c>; the data comes from
/// <see cref="ExampleCatalog"/>. Commands are generated by CommunityToolkit.Mvvm from the
/// <c>[RelayCommand]</c> methods (<c>OpenExamplesBrowser</c> → <c>OpenExamplesBrowserCommand</c>).
/// </para>
/// </remarks>
public sealed partial class MainViewModel
{
    /// <summary>Document to start as soon as the current performance has stopped (see <see cref="SwitchPlaybackTo"/>).</summary>
    DocumentViewModel? playAfterStop;

    /// <summary>Opens (or focuses) the example browser; provided by the view.</summary>
    /// <remarks>
    /// A delegate rather than a window reference because view models never touch Avalonia
    /// windows; <c>MainWindow</c> assigns it at start-up.
    /// </remarks>
    public Action? ShowExamples { get; set; }

    /// <summary>Opens the example browser (toolbar «Ejemplos», Ctrl+E).</summary>
    [RelayCommand]
    void OpenExamplesBrowser() => ShowExamples?.Invoke();

    /// <summary>
    /// Opens the built-in demo (the one shown on first start) in a new untitled tab, in the
    /// interface language. Being untitled, «Save» always asks for a name, so the original inside
    /// the program is never overwritten. If something is playing, the demo replaces it.
    /// </summary>
    [RelayCommand]
    void OpenDemo()
    {
        var doc = AddDocument(LoadDemo(), null);
        doc.UntitledName = "Demo.csd";
        doc.IsDirty = false; // fresh demo: closing the tab must not ask to save
        SelectedDocument = doc;
        FollowWithPlayback(doc);
    }

    /// <summary>Text of the side-panel examples card.</summary>
    public string ExamplesSummary => ExampleCatalog.Summary;

    /// <summary>
    /// Opens an example in a tab (or switches to it). With <paramref name="play"/>, it also plays
    /// it — replacing whatever is playing.
    /// </summary>
    /// <param name="example">The catalog entry chosen in the browser.</param>
    /// <param name="play">True for the browser's «Play» button or «Play on change» mode.</param>
    public void OpenExample(ExampleEntry example, bool play)
    {
        // Browsing should not pile up tabs: the previous example tab is replaced when it has no
        // unsaved changes (like a «preview» tab).
        var previous = Documents.FirstOrDefault(d => ExampleCatalog.Contains(d.FilePath) && !d.IsDirty &&
            !string.Equals(d.FilePath, example.FullPath, StringComparison.OrdinalIgnoreCase));
        // OpenPath selects the existing tab when the file is already open, otherwise adds one
        // (and may already queue a playback switch through FollowWithPlayback).
        OpenPath(example.FullPath);
        // Never remove the only tab: Count > 1 keeps at least the newly opened example.
        if (previous is not null && Documents.Count > 1)
        {
            // The replaced tab is the one sounding and no switch is pending: stop it rather than
            // leave a performance running for a document that no longer has a tab.
            if (lastRunDocument == previous && Mode == RunMode.Play && playAfterStop is null)
                engine.Stop();
            Documents.Remove(previous);
        }
        // Only play when the open actually succeeded (OpenPath leaves the selection unchanged on error).
        if (play && SelectedDocument is { } doc && string.Equals(doc.FilePath, example.FullPath, StringComparison.OrdinalIgnoreCase))
            PlayOrSwitch(doc);
    }

    /// <summary>Plays <paramref name="doc"/>: directly when idle, or after stopping the current performance.</summary>
    /// <param name="doc">Document to play.</param>
    /// <remarks>
    /// Does nothing while rendering to a file (<see cref="RunMode.Render"/>) or when
    /// <paramref name="doc"/> is already the one playing. Play goes through
    /// <c>PlayCommand</c> (not a direct call) so its CanExecute rules still apply.
    /// </remarks>
    public void PlayOrSwitch(DocumentViewModel doc)
    {
        if (Mode == RunMode.None)
        {
            SelectedDocument = doc; // Play always performs the selected document
            if (PlayCommand.CanExecute(null)) PlayCommand.Execute(null);
        }
        else if (Mode == RunMode.Play && lastRunDocument != doc)
            SwitchPlaybackTo(doc);
    }

    /// <summary>
    /// While playing, another document was opened: stop the old performance and start
    /// <paramref name="doc"/> when it has finished (with Play on, the old piece stops and the new
    /// one starts sounding).
    /// </summary>
    /// <param name="doc">Document to play once the engine has finished.</param>
    /// <remarks>Calling it again before the stop completes simply replaces the queued document.</remarks>
    void SwitchPlaybackTo(DocumentViewModel doc)
    {
        playAfterStop = doc;
        AddInfo(Loc.S($"⏭ Cambiando a {doc.FileName}…", $"⏭ Switching to {doc.FileName}…"));
        engine.Stop();
    }

    /// <summary>After opening <paramref name="doc"/>: if something else is playing, play this one instead.</summary>
    /// <param name="doc">The document just opened.</param>
    /// <remarks>Only while playing: when idle, opening a file never starts sound by itself.</remarks>
    void FollowWithPlayback(DocumentViewModel doc)
    {
        if (Mode == RunMode.Play && lastRunDocument != doc)
            SwitchPlaybackTo(doc);
    }

    /// <summary>Called at the end of <c>OnFinished</c>: starts the document queued by <see cref="SwitchPlaybackTo"/>.</summary>
    void StartQueuedPlayback()
    {
        if (playAfterStop is not { } next) return;
        playAfterStop = null;
        if (!Documents.Contains(next)) return; // its tab was closed while the old run was stopping
        SelectedDocument = next;
        if (PlayCommand.CanExecute(null)) PlayCommand.Execute(null);
    }
}
