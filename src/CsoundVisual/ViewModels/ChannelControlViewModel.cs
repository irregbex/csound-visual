using System.Globalization;
using CommunityToolkit.Mvvm.ComponentModel;
using CommunityToolkit.Mvvm.Input;
using CsoundVisual.Localization;

namespace CsoundVisual.ViewModels;

/// <summary>
/// A slider generated from a control channel of the orchestra (<c>chnk</c> declaration or
/// <c>chnget "name"</c> read). Moving it — or dragging the variable in the editor — sends the
/// new value through the <c>send</c> callback given at construction.
/// </summary>
/// <remarks>
/// <para>
/// <b>Who creates it.</b> <see cref="DocumentViewModel.RefreshChannels"/> builds one instance per
/// channel spec found by <see cref="Engine.CsdTools.DetectChannels"/> (merged with Cabbage widget
/// channels by <see cref="Cabbage.CabbageSupport.Merge"/>). Existing instances are reused across
/// re-detections so the value the user set, and any MIDI mapping, survive editing the text.
/// </para>
/// <para>
/// <b>Who consumes it.</b> The side-panel slider list in <c>MainWindow.axaml</c> binds to
/// <see cref="Minimum"/>/<see cref="Maximum"/>/<see cref="Value"/>; Cabbage widgets
/// (<see cref="Cabbage.CabbagePanel"/>), the 3D pad, MIDI learn (<c>MainViewModel.Midi.cs</c>) and
/// the editor's drag-to-scrub all write <see cref="Value"/> too, so every view stays in sync
/// through ordinary property-change notifications.
/// </para>
/// <para>
/// <b>Source generator.</b> Fields marked <c>[ObservableProperty]</c> become public properties
/// (<c>value</c> → <see cref="Value"/>) generated by CommunityToolkit.Mvvm; the generator also
/// calls the optional <c>partial void On…Changed</c> hooks, which is how a value change reaches
/// the engine (<see cref="OnValueChanged(double)"/>). <c>[RelayCommand]</c> on <see cref="ForgetMidi"/>
/// generates <see cref="ForgetMidiCommand"/>.
/// </para>
/// <para>
/// All members are used on the UI thread; the <c>send</c> callback only enqueues the value for
/// the performance thread (see <see cref="Engine.CsoundEngine.SetControl"/>).
/// </para>
/// </remarks>
public sealed partial class ChannelControlViewModel : ObservableObject
{
    /// <summary>
    /// Callback invoked with (channel name, value) on every value change. Supplied by the owning
    /// <see cref="DocumentViewModel"/>, which forwards it to the engine only while that document
    /// is the one playing.
    /// </summary>
    readonly Action<string, double> send;

    /// <summary>Creates a channel control.</summary>
    /// <param name="name">Channel name as used in the orchestra.</param>
    /// <param name="value">Initial value.</param>
    /// <param name="min">Slider minimum.</param>
    /// <param name="max">Slider maximum.</param>
    /// <param name="exponential">True when the channel was declared with an exponential range.</param>
    /// <param name="send">Called with (name, value) whenever the value changes.</param>
    public ChannelControlViewModel(string name, double value, double min, double max, bool exponential, Action<string, double> send)
    {
        Name = name;
        this.send = send;
        minimum = min;
        maximum = max;
        this.value = value;
        Exponential = exponential;
    }

    /// <summary>Channel name.</summary>
    public string Name { get; }

    /// <summary>True when the declared range is exponential (frequency-like).</summary>
    /// <remarks>
    /// Plain auto-property (no change notification): it is only read when a value is mapped from a
    /// normalised 0…1 source (MIDI learn, 3D pad, analyzer ranges), never bound in XAML.
    /// Re-detection (<see cref="DocumentViewModel.RefreshChannels"/>) may update it in place.
    /// </remarks>
    public bool Exponential { get; set; }

    /// <summary>Slider minimum (generated property <c>Minimum</c>); follows the declaration on re-detection.</summary>
    [ObservableProperty] double minimum;

    /// <summary>Slider maximum (generated property <c>Maximum</c>); follows the declaration on re-detection.</summary>
    [ObservableProperty] double maximum;

    /// <summary>
    /// Current value in the channel's own units (generated property <c>Value</c>); setting it sends
    /// it to the engine (when the document is playing) and refreshes <see cref="DisplayValue"/>.
    /// </summary>
    [ObservableProperty]
    [NotifyPropertyChangedFor(nameof(DisplayValue))]
    double value;

    /// <summary>
    /// True while waiting for a MIDI controller to be moved (MIDI learn). Set by the learn button;
    /// cleared by <c>MainViewModel.ProcessMidi</c> when the first CC arrives.
    /// </summary>
    [ObservableProperty]
    [NotifyPropertyChangedFor(nameof(LearnText))]
    bool isLearning;

    /// <summary>
    /// Display label of the MIDI controller mapped to this slider ("CC 74 · ch 1"), or <c>null</c>.
    /// Only a label: the mapping itself is stored by <see cref="MainViewModel"/> (and persisted in
    /// the settings), which writes this text so the button can show it.
    /// </summary>
    [ObservableProperty]
    [NotifyPropertyChangedFor(nameof(LearnText), nameof(HasMidiBinding))]
    [NotifyCanExecuteChangedFor(nameof(ForgetMidiCommand))]
    string? midiBinding;

    /// <summary>
    /// Handler that removes a slider's MIDI mapping, installed once by <see cref="MainViewModel"/>.
    /// </summary>
    /// <remarks>
    /// The "Quitar asignación MIDI" item lives in a context menu, which opens in a popup outside
    /// the window's visual tree. A <c>$parent[ItemsControl]</c> binding cannot reach the main view
    /// model from there; Avalonia then disables the menu item because its Command binding failed
    /// (that was the bug: the item was always grey). Binding to this per-slider command avoids it.
    /// </remarks>
    public static Action<ChannelControlViewModel>? ForgetMidiHandler { get; set; }

    /// <summary>
    /// Removes the MIDI mapping of this slider (enabled only when one exists). Generates
    /// <see cref="ForgetMidiCommand"/>; its CanExecute is re-queried whenever
    /// <see cref="MidiBinding"/> changes (<c>[NotifyCanExecuteChangedFor]</c> above).
    /// </summary>
    [RelayCommand(CanExecute = nameof(HasMidiBinding))]
    void ForgetMidi() => ForgetMidiHandler?.Invoke(this);

    /// <summary>True when a controller is mapped.</summary>
    public bool HasMidiBinding => MidiBinding is not null;

    /// <summary>
    /// Text of the MIDI learn button: a localised prompt while learning, otherwise the mapped
    /// controller label, otherwise just "MIDI".
    /// </summary>
    public string LearnText => IsLearning ? Loc.S("mueve un control…", "move a control…") : MidiBinding ?? "MIDI";

    /// <summary>Value formatted with a precision appropriate for its magnitude.</summary>
    /// <remarks>
    /// Three significant-ish digits: integers from 100 up (e.g. a cutoff of "1800"), one decimal
    /// from 10, three decimals below (e.g. "0.406"). Invariant culture so the decimal separator
    /// is always a dot, matching Csound syntax, regardless of the Windows locale.
    /// </remarks>
    public string DisplayValue =>
        Value.ToString(Math.Abs(Value) >= 100 ? "0" : Math.Abs(Value) >= 10 ? "0.0" : "0.000", CultureInfo.InvariantCulture);

    /// <summary>
    /// Source-generator hook called after <see cref="Value"/> changed (not when it is set to the
    /// same value): forwards the new value to the owner's <see cref="send"/> callback.
    /// </summary>
    /// <param name="value">The new value.</param>
    partial void OnValueChanged(double value) => send(Name, value);

    /// <summary>Sends the current value again (used right before a performance starts).</summary>
    /// <remarks>
    /// A new Csound instance starts with the channel defaults of the orchestra; re-sending makes
    /// it start with what the sliders currently show (called by <c>MainViewModel</c> for every
    /// channel of the document being played).
    /// </remarks>
    public void Resend() => send(Name, Value);
}
