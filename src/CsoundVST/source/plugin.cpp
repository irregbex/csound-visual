/// Runs on whatever thread the host creates plug-ins on (normally the UI thread).
/// Only cheap member setup: the std::atomic arrays are not value-initialised by
/// their default constructors, hence the explicit stores.
CsoundVisualPlugin::CsoundVisualPlugin (PluginKind k) : kind (k)
{
	instanceNumber = ++gInstanceCounter;
	csdText = kind == PluginKind::Fx ? kDefaultFxCsd : kDefaultInstrumentCsd;
	for (auto& p : paramNorm)
		p.store (0.0);
	for (auto& p : midiParamNorm)
		p.store (0.0);
	for (int ch = 0; ch < kNumMidiChannels; ++ch)
		midiParamNorm[ch * kNumMidiParams + 0].store (0.5); // pitch bend (idx 0) rests at centre
	for (auto& e : pendingEdit)
		e.store (false);
	latency.store (32); // ksmps of the default orchestras

	// IProcessContextRequirements (VST 3.7+): tell the host which ProcessContext fields
	// we read, so it fills tempo, play state and musical position (for HOST_BPM,
	// HOST_PLAYING and HOST_PPQ).
	processContextRequirements.needTempo ().needTransportState ().needProjectTimeMusic ();
}

/// Final release by the host. Mirrors terminate() for the IPC thread and the Csound
/// instance (both safe to repeat). Stopping IPC first guarantees handleIpc() is not
/// running while the instance is destroyed. Locks are taken in the usual order
/// (lifetimeMutex, then swapMutex).
CsoundVisualPlugin::~CsoundVisualPlugin ()
{
	ipc.stop ();
	// Hosts that skip terminate() would otherwise leave the descriptor file (the app
	// would list a dead instance until the process exits) and, worse, the hidden window
	// with GWLP_USERDATA still pointing at this freed object: a kMsgUiUpdate already in
	// the queue would then call applyUiUpdate() on freed memory. Both calls are no-ops
	// after a normal terminate().
	removeDescriptor ();
	destroyUiWindow ();
	std::lock_guard<std::mutex> l1 (lifetimeMutex);
	std::lock_guard<std::mutex> l2 (swapMutex);
	active.reset ();
}

/// Detach first (SetWindowLongPtrW works from any thread of the process): a kMsgUiUpdate
/// still queued then finds no plug-in and is ignored by uiWndProc. DestroyWindow only
/// works on the window's own thread (the one that called initialize()); from any other
/// thread (a host may release the last reference elsewhere) we post WM_CLOSE instead,
/// which DefWindowProcW turns into DestroyWindow on the owning thread. The window class
/// itself stays registered for the life of the DLL.
void CsoundVisualPlugin::destroyUiWindow ()
{
	if (!uiWindow)
		return;
	HWND hwnd = static_cast<HWND> (uiWindow);
	uiWindow = nullptr;
	SetWindowLongPtrW (hwnd, GWLP_USERDATA, 0);
	if (GetWindowThreadProcessId (hwnd, nullptr) == GetCurrentThreadId ())
		DestroyWindow (hwnd);
	else
		PostMessageW (hwnd, WM_CLOSE, 0, 0);
}

