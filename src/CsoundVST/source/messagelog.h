//------------------------------------------------------------------------------
// Csound Visual VST3 - thread-safe ring buffer of Csound message lines
//
// Csound calls the message callback on whatever thread produced the message:
// usually the compile thread (IPC / UI thread), sometimes the audio thread
// (print opcodes during performance). Every public method takes a short mutex,
// so this class must NOT be called from the audio thread: messages produced
// there are pushed into a lock-free FIFO instead (EngineShared::audioThreadText,
// see csoundengine.cpp) and moved here later by drainAudioThreadMessages() on a
// non-audio thread. The log therefore only ever blocks IPC/UI threads, briefly.
//
// Roles:
//   * keeps the last `maxLines` lines (default 200) for the IPC "status" reply;
//   * optionally captures every line between beginCapture() and endCapture(),
//     which the IPC "load" command uses to return exactly the messages of one
//     compile;
//   * reassembles Csound's message fragments into lines and strips ANSI colour
//     escape sequences (Csound colours errors/warnings on terminals).
//
// Ownership: one MessageLog per plug-in instance, inside EngineShared.
//------------------------------------------------------------------------------
#pragma once

#include <deque>
#include <mutex>
#include <string>

namespace CsoundVisual {

/// Bounded, thread-safe log of Csound and plug-in message lines (see file header).
class MessageLog
{
public:
	/// @param maxLines number of complete lines kept for text(); older lines are dropped.
	explicit MessageLog (size_t maxLines = 200) : maxLines (maxLines) {}

	/// Appends a raw fragment as delivered by Csound. Fragments are joined until a newline;
	/// ANSI colour escapes are stripped. Every completed line is also appended to the
	/// capture buffer if a capture is active (see beginCapture()).
	void append (const char* text)
	{
		if (!text)
			return;
		std::lock_guard<std::mutex> lock (mutex);
		for (const char* c = text; *c; ++c)
		{
			if (*c == '\x1b')
			{
				// Skip "ESC [ ... m" (SGR colour/style sequence). The sequence must be
				// complete within this fragment; an ESC that does not start a complete
				// "ESC[...m" is kept as an ordinary character.
				const char* e = c + 1;
				if (*e == '[')
				{
					++e;
					while (*e && *e != 'm')
						++e;
					if (*e == 'm')
					{
						c = e;
						continue;
					}
				}
			}
			if (*c == '\n')
				commitLine ();
			else if (*c != '\r') // CR is dropped so CRLF and LF produce the same lines
				partial += *c;
		}
	}

	/// Adds a complete line generated by the plug-in itself (no trailing newline needed).
	/// A pending partial Csound line is committed first so the two never get merged.
	void line (const std::string& text)
	{
		std::lock_guard<std::mutex> lock (mutex);
		if (!partial.empty ())
			commitLine ();
		partial = text;
		commitLine ();
	}

	/// Starts collecting every following line (used to return the log of one compile).
	/// Discards any previous capture. Captures do not nest. Lines from any thread
	/// (including drained audio-thread text) are captured while active.
	void beginCapture ()
	{
		std::lock_guard<std::mutex> lock (mutex);
		capturing = true;
		capture.clear ();
	}

	/// Stops collecting and returns the captured text (pending partial line included).
	std::string endCapture ()
	{
		std::lock_guard<std::mutex> lock (mutex);
		if (!partial.empty ())
			commitLine ();
		capturing = false;
		std::string out;
		out.swap (capture);
		return out;
	}

	/// Returns the last lines joined by '\n' (each followed by '\n'), plus the pending
	/// partial line without a newline. Returns a copy; safe from any non-audio thread.
	std::string text () const
	{
		std::lock_guard<std::mutex> lock (mutex);
		std::string out;
		for (const auto& l : lines)
		{
			out += l;
			out += '\n';
		}
		if (!partial.empty ())
			out += partial;
		return out;
	}

private:
	/// Moves `partial` into the ring (and into the capture, if active) and trims the ring.
	/// Caller must hold `mutex`. The capture is capped at 256 KiB so a runaway orchestra
	/// printing during a compile cannot grow the IPC reply without bound.
	void commitLine ()
	{
		if (capturing && capture.size () < 256 * 1024)
		{
			capture += partial;
			capture += '\n';
		}
		lines.push_back (std::move (partial));
		partial.clear ();
		while (lines.size () > maxLines)
			lines.pop_front ();
	}

	mutable std::mutex mutex;        ///< guards every member below; mutable for text() const
	size_t maxLines;                 ///< ring capacity in lines
	std::deque<std::string> lines;   ///< completed lines, oldest first
	std::string partial;             ///< current line being assembled (no newline yet)
	bool capturing = false;          ///< between beginCapture() and endCapture()
	std::string capture;             ///< captured lines, '\n'-terminated
};

} // namespace CsoundVisual
