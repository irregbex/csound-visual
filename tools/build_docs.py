def build():
    """Generate the whole site into ``docs/html``.

    Output layout::

        docs/html/index.html          redirect to es/index.html (Spanish is the default language)
        docs/html/style.css, app.png  shared assets (app.png = the app icon, if present)
        docs/html/en/<stem>.html      one page per entry of PAGES["en"]
        docs/html/es/<stem>.html      one page per entry of PAGES["es"]

    The previous output folder is removed first, so pages dropped from ``PAGES`` disappear.
    """
    global _src_dir, _out_dir  # per-page context read by image()
    if OUT.exists():
        shutil.rmtree(OUT)
    OUT.mkdir(parents=True)
    (OUT / "style.css").write_text(CSS, encoding="utf8")
    icon = ROOT / "src" / "CsoundVisual" / "Assets" / "app.png"
    if icon.exists():
        shutil.copy(icon, OUT / "app.png")

    for lang, pages in PAGES.items():
        (OUT / lang).mkdir()
        for index, (stem, title) in enumerate(pages):
            src = DOCS / lang / f"{stem}.md"
            # image() resolves relative image paths against the folder of the page being
            # converted (docs/<lang>) and links them from the output folder (html/<lang>).
            _src_dir, _out_dir = DOCS / lang, OUT / lang
            body = convert(src.read_text(encoding="utf8")) if src.exists() else f"<h1>{title}</h1><p>(pendiente)</p>"
            # Sidebar: every page of this language, the current one highlighted ("on").
            nav = "".join(f'<a class="{"on" if s == stem else ""}" href="{s}.html">{html.escape(t)}</a>' for s, t in pages)
            # Language switcher: links to the page at the same index in the other language
            # (stems differ, e.g. user-guide <-> guia-de-usuario). (The unused `other`
            # variable that used to sit here was removed.)
            langs = "".join(
                f'<a class="{"on" if l == lang else ""}" href="../{l}/{(PAGES[l][index][0])}.html">{LANG_NAME[l]}</a>'
                for l in ("en", "es"))
            page = TEMPLATE.format(lang=lang, title=html.escape(title), langs=langs, nav=nav, body=body)
            (OUT / lang / f"{stem}.html").write_text(page, encoding="utf8")

    # Root entry point: an instant meta-refresh to the Spanish overview, with plain links as a
    # fallback for browsers that block the refresh.
    (OUT / "index.html").write_text(
        '<!doctype html><meta charset="utf-8"><meta http-equiv="refresh" content="0; url=es/index.html">'
        '<title>Csound Visual</title><a href="es/index.html">Español</a> · <a href="en/index.html">English</a>',
        encoding="utf8")
    print("docs built in", OUT)


if __name__ == "__main__":
    build()
