def inline(text: str) -> str:
    """Convert inline Markdown inside one block (paragraph, heading, list item, table cell) to HTML.

    Order matters:

    1. Code spans are cut out first and replaced by ``\\x00<n>\\x00`` placeholders, so nothing
       inside backticks is treated as emphasis or links.
    2. The rest is HTML-escaped (``quote=False``: quotes stay readable in text).
    3. Images, then links (images first, because ``![..](..)`` also matches the link pattern).
    4. ``**bold**``, then ``*italic*`` (the look-arounds keep ``a*b*c`` and ``**`` untouched).
    5. The placeholders are replaced by ``<code>`` elements with the escaped code.

    Args:
        text: raw Markdown of the block (may contain several lines joined by spaces).

    Returns:
        The HTML fragment (not wrapped in any block element).
    """
    codes = []

    def keep_code(m):
        """Store an escaped code span and return its NUL-delimited placeholder."""
        codes.append(html.escape(m.group(1)))
        return f"\x00{len(codes) - 1}\x00"

    text = re.sub(r"`([^`]+)`", keep_code, text)
    text = html.escape(text, quote=False)
    text = re.sub(r"!\[([^\]]*)\]\(([^)]+)\)", lambda m: image(m.group(2), m.group(1)), text)
    text = re.sub(r"\[([^\]]+)\]\(([^)]+)\)", lambda m: f'<a href="{link(m.group(2))}">{m.group(1)}</a>', text)
    text = re.sub(r"\*\*([^*]+)\*\*", r"<strong>\1</strong>", text)
    text = re.sub(r"(?<![\w*])\*([^*\s][^*]*)\*(?![\w*])", r"<em>\1</em>", text)
    return re.sub(r"\x00(\d+)\x00", lambda m: f"<code>{codes[int(m.group(1))]}</code>", text)


def link(url: str) -> str:
    """Rewrite a Markdown link target for the HTML site.

    External URLs, in-page anchors and ``mailto:`` links are returned unchanged. Relative links to
    another ``.md`` page become ``.html`` (keeping any ``#anchor``), so cross-references written for
    GitHub's Markdown view also work in the generated site.

    Args:
        url: the link target as written in the Markdown (already HTML-escaped by ``inline``).

    Returns:
        The href to emit.
    """
    if url.startswith(("http://", "https://", "#", "mailto:")):
        return url
    return re.sub(r"\.md(#|$)", r".html\1", url)


# Folder of the Markdown page being converted (docs/<lang>) and of its HTML output
# (docs/html/<lang>). Set by build() before each page; read by image() so relative image paths
# are resolved like a Markdown viewer would (relative to the page's own folder).
_src_dir: Path = DOCS / "en"
_out_dir: Path = OUT / "en"


def image(src: str, alt: str) -> str:
    """Render a Markdown image: SVG diagrams are inlined; other images are referenced.

    Inlining lets the diagrams inherit the page's CSS (fonts, colours) and keeps the site a set
    of self-contained pages with no separate image files to copy. A relative path is resolved
    against the folder of the page being converted (``_src_dir``, i.e. ``docs/en`` or
    ``docs/es``). Before, it was always resolved against ``docs/en``, which only worked
    because both languages happen to write ``../diagrams/<name>.svg``; a Spanish-only image
    or a different relative path silently broke. A non-SVG image (or an SVG that cannot be
    found) becomes an ``<img>`` whose path is rewritten relative to the output folder
    (``docs/html/<lang>``), so it still points at the same file from the generated page.

    Args:
        src: image path as written in the Markdown.
        alt: alt text; also used as the figure caption and ARIA label.

    Returns:
        A ``<figure class="diagram">`` with the inline SVG, or an ``<img>`` element.
    """
    # inline() has already HTML-escaped the text (quote=False), so undo that for the file
    # lookup; the attribute is escaped again (quotes included) when it is written out.
    src = html.unescape(src)
    is_remote = src.startswith(("http://", "https://", "data:", "/"))
    path = None if is_remote else (_src_dir / src).resolve()
    if src.endswith(".svg") and path is not None and path.exists():
        svg = path.read_text(encoding="utf8")
        # An XML declaration is not allowed in the middle of an HTML document.
        svg = re.sub(r"<\?xml[^>]*\?>", "", svg)
        return f'<figure class="diagram" role="img" aria-label="{html.escape(alt)}">{svg}<figcaption>{html.escape(alt)}</figcaption></figure>'
    if path is not None and path.exists():
        # Same file, addressed from the generated page's folder (forward slashes for URLs).
        src = os.path.relpath(path, _out_dir).replace(os.sep, "/")
    return f'<img src="{html.escape(src, quote=True)}" alt="{html.escape(alt)}">'


def convert(md: str) -> str:
    """Convert a whole Markdown document (or a block-quote body) to HTML.

    A single forward pass over the lines; at each position the first matching block type wins,
    in this order: fenced code, heading (``#``..``####``), horizontal rule, table, block quote,
    list, blank line, paragraph. Each branch consumes all the lines of its block and advances
    ``i``. Block quotes recurse into ``convert`` for their content.

    Args:
        md: Markdown text (CRLF or LF line endings).

    Returns:
        HTML, one block element per line.
    """
    lines = md.replace("\r\n", "\n").split("\n")
    out, i = [], 0
    while i < len(lines):
        line = lines[i]
        # Fenced code block: everything up to the closing ``` is escaped verbatim; the info
        # string becomes a "lang-<x>" class (no syntax highlighting is applied).
        if line.startswith("```"):
            lang = line[3:].strip()
            j = i + 1
            while j < len(lines) and not lines[j].startswith("```"):
                j += 1
            code = html.escape("\n".join(lines[i + 1:j]))
            out.append(f'<pre><code class="lang-{lang}">{code}</code></pre>')
            i = j + 1
            continue
        if m := re.match(r"^(#{1,4})\s+(.*)$", line):
            level = len(m.group(1))
            # GitHub-like slug (lower case, runs of non-word characters -> "-") so that
            # "page.md#some-heading" links keep working after conversion.
            anchor = re.sub(r"[^\w]+", "-", m.group(2).lower()).strip("-")
            out.append(f'<h{level} id="{anchor}">{inline(m.group(2))}</h{level}>')
            i += 1
            continue
        if re.match(r"^\s*(---|\*\*\*)\s*$", line):
            out.append("<hr>")
            i += 1
            continue
        # Pipe table: the first row is the header; the "|---|:--:|" separator row is dropped.
        # Column alignment markers are ignored.
        if line.startswith("|"):
            rows = []
            while i < len(lines) and lines[i].startswith("|"):
                rows.append([c.strip() for c in lines[i].strip().strip("|").split("|")])
                i += 1
            head, body = rows[0], [r for r in rows[1:] if not all(re.match(r"^:?-+:?$", c) for c in r)]
            t = "<table><thead><tr>" + "".join(f"<th>{inline(c)}</th>" for c in head) + "</tr></thead><tbody>"
            t += "".join("<tr>" + "".join(f"<td>{inline(c)}</td>" for c in r) + "</tr>" for r in body)
            out.append(t + "</tbody></table>")
            continue
        if line.startswith(">"):
            quote = []
            while i < len(lines) and lines[i].startswith(">"):
                quote.append(lines[i][1:].strip())
                i += 1
            out.append("<blockquote>" + convert("\n".join(quote)) + "</blockquote>")
            continue
        if re.match(r"^(\s*)([-*]|\d+\.)\s+", line):
            out.append(convert_list(lines, i))
            # Skip the lines convert_list consumed (same rule: item lines and indented
            # continuation lines).
            while i < len(lines) and (re.match(r"^(\s*)([-*]|\d+\.)\s+", lines[i]) or (lines[i].startswith("  ") and lines[i].strip())):
                i += 1
            continue
        if not line.strip():
            i += 1
            continue
        # Paragraph: consecutive non-blank lines until a line that starts another block type.
        para = [line]
        i += 1
        while i < len(lines) and lines[i].strip() and not re.match(r"^(#{1,4}\s|```|\||>|\s*([-*]|\d+\.)\s)", lines[i]):
            para.append(lines[i])
            i += 1
        out.append("<p>" + inline(" ".join(p.strip() for p in para)) + "</p>")
    return "\n".join(out)


def convert_list(lines, i) -> str:
    """A list starting at line i; items indented by 2+ spaces nest one level.

    Items are first collected as ``[indent, ordered, text]``; a non-item line that starts with two
    spaces is a continuation of the previous item's text. The first item decides the list type
    (``<ol>`` for ``1.``, ``<ul>`` for ``-``/``*``); an item indented more than the first one
    opens a sub-list inside the previous ``<li>`` (deeper levels are flattened into that one
    sub-list). The caller skips the consumed lines itself.

    Args:
        lines: all lines of the document.
        i: index of the first item line.

    Returns:
        The list HTML on a single line.
    """
    items = []  # (indent, ordered, text)
    while i < len(lines):
        m = re.match(r"^(\s*)([-*]|\d+\.)\s+(.*)$", lines[i])
        if m:
            items.append([len(m.group(1)), m.group(2)[0].isdigit(), m.group(3)])
        elif lines[i].startswith("  ") and lines[i].strip() and items:
            items[-1][2] += " " + lines[i].strip()
        else:
            break
        i += 1
    base = items[0][0]
    tag = "ol" if items[0][1] else "ul"
    html_out, open_sub = [f"<{tag}>"], None
    for indent, ordered, text in items:
        if indent > base:
            if open_sub is None:
                open_sub = "ol" if ordered else "ul"
                # Re-open the previous <li> so the sub-list is nested inside it (valid HTML).
                html_out[-1] = html_out[-1].removesuffix("</li>") + f"<{open_sub}>"
            html_out.append(f"<li>{inline(text)}</li>")
        else:
            if open_sub:
                html_out.append(f"</{open_sub}></li>")
                open_sub = None
            html_out.append(f"<li>{inline(text)}</li>")
    if open_sub:
        html_out.append(f"</{open_sub}></li>")
    html_out.append(f"</{tag}>")
    return "".join(html_out)


