"""Builds the HTML documentation site of Csound Visual from the Markdown sources.

Usage:  python tools/build_docs.py
Input:  docs/en/*.md, docs/es/*.md, docs/diagrams/*.svg
Output: docs/html/  (open docs/html/index.html in a browser; works offline)

The converter below is intentionally small and dependency-free. It supports the Markdown used
in these docs: headings, paragraphs, bullet/numbered lists (with one level of nesting), tables,
fenced code blocks, block quotes, horizontal rules, images, links (``.md`` links are rewritten
to ``.html``), inline code, bold and italics. Diagrams are inlined as SVG so they inherit the
page colours and stay sharp at any zoom.

Role in the project: the generated ``docs/html`` folder is what ``tools/package.ps1`` copies into
the release as ``Docs/``; it is regenerated by hand (``python tools/build_docs.py``) after editing
the Markdown, never by the app or the .NET build. The whole output folder is deleted and rebuilt
on every run.

Design decisions:

* No third-party Markdown library, so the build needs nothing but a stock Python 3.9+
  (``str.removesuffix`` and the walrus operator are used). Unsupported Markdown simply comes
  out as a paragraph of text.
* Every page is a static file with relative links only, so the site works from ``file://``
  and inside the zip without a web server.
* Both languages share the same page list order, which is how the language switcher maps a
  page to its translation (same index in ``PAGES[lang]``).
"""
